#!/usr/bin/env python3
"""Convert selected WordCraft Pen primitives to trusted, monochrome SVG authoring files.

The coordinates below are copied from the MIT-licensed original in
third_party/wordcraft/upstream/icons.rs at ae5c65b9dd11faf359ce039a2a487e57e3d824a2.
This is an offline authoring tool, not a runtime dependency. Accent colours become
ink in Holonomy's 1-bit atlas; transparent/tinted fills that fall below its alpha
threshold are omitted. Text-bearing icons retain Holonomy's existing atlas masks.
Run from the repository root: python3 tools/port_wordcraft_icons.py
"""
from pathlib import Path
import math

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "crates/holonomy-render/assets/icons"
REV = "ae5c65b9dd11faf359ce039a2a487e57e3d824a2"

def line(*points): return ("line", points)
def closed(*points): return ("closed", points)
def fill(*points): return ("fill", points)
def rect(x0, y0, x1, y1): return ("rect", (x0, y0, x1, y1))
def frect(x0, y0, x1, y1): return ("frect", (x0, y0, x1, y1))
def circle(x, y, r): return ("circle", (x, y, r))
def fcircle(x, y, r): return ("fcircle", (x, y, r))
def lines(x0, x1, ys): return [line((x0, y), (x1, y)) for y in ys]

# Names are WordCraft's; values are its original 20x20 Pen coordinates.
ICONS = {
    "paste": [rect(4,3.5,14,17), frect(7,2,11,5), rect(9,8,17.5,18.5), *lines(10.8,15.8,[11,13.5,16])],
    "cut": [circle(6,15,2.5), circle(14,15,2.5), line((7.5,13),(14,3)), line((12.5,13),(6,3))],
    "copy": [rect(3.5,3,12.5,14), rect(7.5,6.5,16.5,17.5)],
    "save": [closed((3,3),(14,3),(17,6),(17,17),(3,17)), frect(6,3,13,7.5), rect(6,11,14,17)],
    "search": [circle(8.5,8.5,5), line((12,12),(16.5,16.5))],
    "find": [circle(8,8,5), line((11.5,11.5),(17,17))],
    "bullets": [item for y in [5,10,15] for item in (fcircle(4,y,1.4), line((7.5,y),(17,y)))],
    "align-left": [*lines(3,17,[4,10,16]), *lines(3,12,[7,13])],
    "align-center": [*lines(3,17,[4,10,16]), *lines(6,14,[7,13])],
    "align-right": [*lines(3,17,[4,10,16]), *lines(8,17,[7,13])],
    "indent": [*lines(9,17,[7,10,13]), *lines(3,17,[3.5,16.5]), fill((3,7),(3,13),(6.5,10))],
    "outdent": [*lines(9,17,[7,10,13]), *lines(3,17,[3.5,16.5]), fill((6.5,7),(6.5,13),(3,10))],
    "table": [frect(3,3,17,7), rect(3,3,17,17), line((3,7),(17,7)), line((3,12),(17,12)), line((8,3),(8,17)), line((12.5,3),(12.5,17))],
    "picture": [rect(3,4.5,17,15.5), fill((4.5,14),(8.5,8.5),(12,14)), fill((10,14),(13,10.5),(15.5,14)), fcircle(13.5,7,1.3)],
    "page-break": [line((4,2),(4,7),(16,7),(16,2)), line((4,18),(4,13),(16,13),(16,18)), line((2,10),(18,10))],
    "navigation": [rect(3,3,17,17), frect(3,3,8,17)],
    "theme": [frect(10,3.5,17.5,16.5), rect(2.5,3.5,17.5,16.5), line((2.5,6.5),(10,6.5))],
    "close": [line((5,5),(15,15)), line((15,5),(5,15))],
    "chevron-up": [line((4,13),(10,7),(16,13))],
    "chevron-down": [line((4,7),(10,13),(16,7))],
    "more": [fcircle(x,10,1.3) for x in [5,10,15]],
}
# The upstream undo/redo arcs are sampled exactly as in the original Pen code.
undo_arc = [(13+4.5*math.cos(-math.pi/2+math.pi*i/12), 12.5+4.5*math.sin(-math.pi/2+math.pi*i/12)) for i in range(13)]
redo_arc = [(7+4.5*math.cos(math.pi/2+math.pi*i/12), 12.5-4.5*math.sin(math.pi/2+math.pi*i/12)) for i in range(13)]
ICONS["undo"] = [line((5,8),(13,8)), line(*undo_arc), line((13,17),(8,17)), fill((2.5,8),(6.5,4.5),(6.5,11.5))]
ICONS["redo"] = [line((15,8),(7,8)), line(*redo_arc), line((7,17),(12,17)), fill((17.5,8),(13.5,4.5),(13.5,11.5))]

def number(v): return f"{v:g}"
def point(p): return " ".join(map(number, p))
def path(kind, data):
    if kind in ("line", "closed", "fill"):
        d = "M " + " L ".join(point(p) for p in data) + (" Z" if kind != "line" else "")
    elif kind in ("rect", "frect"):
        x0,y0,x1,y1 = data
        d = f"M {number(x0)} {number(y0)} H {number(x1)} V {number(y1)} H {number(x0)} Z"
    else:
        x,y,r = data
        d = f"M {number(x-r)} {number(y)} A {number(r)} {number(r)} 0 1 0 {number(x+r)} {number(y)} A {number(r)} {number(r)} 0 1 0 {number(x-r)} {number(y)} Z"
    filled = kind in ("fill", "frect", "fcircle")
    return f'  <path d="{d}" fill="{"black" if filled else "none"}" stroke="{"none" if filled else "black"}"/>'

def main():
    source = (ROOT / "third_party/wordcraft/upstream/icons.rs").read_text()
    for upstream in ("save", "undo", "redo", "paste", "cut", "copy", "navPane", "interfaceTheme"):
        assert f'"{upstream}"' in source, f"missing upstream source: {upstream}"
    OUT.mkdir(parents=True, exist_ok=True)
    for name, primitives in ICONS.items():
        svg = '<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 20 20" stroke-width="1.25" stroke-linecap="round" stroke-linejoin="round">\n'
        svg += f"  <!-- MIT, WordCraft contributors; {REV}. Generated by tools/port_wordcraft_icons.py. -->\n"
        svg += "\n".join(path(*p) for p in primitives) + "\n</svg>\n"
        assert len(svg.encode()) <= 2048, name
        (OUT / f"wordcraft-{name}.svg").write_text(svg)
    print(f"Generated {len(ICONS)} WordCraft icons from MIT source {REV}")

if __name__ == "__main__":
    main()
