/**
 * Take the user to a search hit: scroll the section into the window, focus it, and put the
 * caret on the match.
 *
 * # Why the caret is placed by walking the text rather than by clicking
 *
 * `posAtCoords` answers "which document position is at this pixel", which is the wrong
 * direction: it needs a pixel, and the only way to get one is to know where the match is.
 * The section's own ProseMirror document already contains the text, so the position is a
 * `textBetween` walk — exact, and independent of layout, font metrics and scroll offsets,
 * all of which `posAtCoords` depends on.
 *
 * The snippet comes back with `<b>` markers which are *not* in the document text, so the
 * query is re-derived from what the user typed rather than from the snippet.
 */
async function goToSearchHit(hit: { section_id: string }, query: string): Promise<void> {
  const index = booted?.payload.sections.findIndex(s => s.id === hit.section_id) ?? -1
  if (index < 0) return

  // Mount and scroll *before* focusing. `registry.focus` mounts the editor but the section
  // may be 1,200 sections away, so focusing first would move the caret in a section the
  // user cannot see, and the scroller would then move the viewport under it.
  const y = await geometry.offsetOf(index)
  scrollerEl.scrollTop = y
  await scroller?.refresh()

  if (!registry.focus(hit.section_id)) return
  await new Promise(r => setTimeout(r, 30))

  const editor = registry.editorIfMounted(hit.section_id) as unknown as {
    state?: { doc: { descendants: (f: (node: any, offset: number, index: number, parent: any) => boolean) => void; textBetween: (a: number, b: number, s?: string) => string }; textContent: string }
    dispatch: (tr: any) => void
    commands: { setTextSelection?: (p: number) => void; focus: () => void }
  } | null
  if (!editor?.state || !editor.commands) return

  // `posAtCoords` was rejected for this; see above. What is left is: find the run of text
  // equal to the query, and turn its offset into a document position.
  //
  // `doc.descendants` gives each text node's start position, so the offset of the match
  // inside that node is a document position directly. Case-insensitive, because FTS5's
  // unicode61 fold is case-insensitive and a search for "Hyde" must find "hyde".
  const needle = query.trim().toLowerCase()
  let found = -1
  if (needle) {
    editor.state.doc.descendants((node: any, pos: number) => {
      // Returning false stops the walk, so a document whose first paragraph matches costs
      // one node rather than all fifteen hundred.
      if (found >= 0 || !node.isText) return found < 0
      const at = (node.text ?? '').toLowerCase().indexOf(needle)
      if (at >= 0) found = pos + at
      return found < 0
    })
  }
  // Focus either way. A query that matched nothing still leaves the user in the right
  // section, which is the useful outcome: they see the text and can see why it did not match.
  if (found > 0) editor.commands.setTextSelection?.(found)
  editor.commands.focus()
}

const searchPanel = createSearchPanel({
  search: query => searchDocument(query, 50),
  onNavigate: goToSearchHit,
})

/**
 * Wire the native menu's commands.
 *
 * # Why the menu routes here rather than acting in Rust
 *
 * Because the three commands are three different things: `Find` is frontend state, `Backup`
 * is a native dialog, and `Optimize` is a store operation whose report has to be *shown*.
 * Handling them in one place is what keeps the menu and `Cmd+F` on a single path — and a
 * second path to one operation is how two paths to it drift.
 *
 * # Why a failed subscription is not fatal
 *
 * `onMenuCommand` throws when there is no Tauri event host, which is the browser test
 * harness rather than the application. Boot must not fail there: the harness drives the same
 * operations through `HOLO_SCROLL`, and the menu does not exist in a browser at all. The
 * error is logged so a *real* failure — a running app with no event host — is visible, and
 * swallowed so a non-Tauri environment still starts.
 */
function attachMenu(): void {
  const notice = document.getElementById('notice')

  void onMenuCommand((command: MenuCommandId) => {
    switch (command) {
      case 'find':
        // `open`, not a toggle: pressing `Cmd+F` while the panel is already open should
        // re-focus the input and select its text, which is what every editor does and what
        // a toggle would refuse to do.
        searchPanel.open()
        break

      case 'backup':
        void runBackup(notice)
        break

      case 'optimize':
        void runOptimize(notice)
        break

      default:
        // Unreachable while `MenuCommandId` and the Rust enum agree; logged rather than
        // ignored so a newly added menu item that is not wired up is visible in a log
        // rather than being a button that does nothing.
        console.warn(`[holonomy] no handler for menu command ${String(command)}`)
    }
  }).catch((e: unknown) => {
    console.warn('[holonomy] native menu unavailable', e)
  })
}

