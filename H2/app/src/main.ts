/** Height for a section from its metrics, using the same model as Rust. */
/**
 * Estimated height for an unmeasured section.
 *
 * # There is no fallback here, on purpose
 *
 * An earlier version ended with `blocks ?? Math.max(1, chars / 620)` — deriving the
 * block count from the character count when the caller did not supply one. That
 * fallback measured at 225% error on short multi-paragraph sections and 41% on long
 * single-paragraph ones, because the same character count can be one paragraph or
 * twenty and no constant density recovers that.
 *
 * Deleting the fallback is the point. `metrics.blocks` is now a required field, so
 * a caller that cannot supply it gets a type error at the call site instead of a
 * scrollbar that is quietly wrong for every section it never rendered. Rust keeps
 * its own fallback for rows written before `block_count` existed, but nothing on
 * the frontend reaches it — and there is a test asserting exactly that.
 *
 * # On `chars.max(words * 4)`
 *
 * A section's character count is authoritative when it has been counted. The `max`
 * is a floor for the case where only a word count is known, so the estimate cannot
 * collapse to zero for a section that plainly has text in it.
 */
function estimateHeight(m: SectionRecord['metrics']): number {
  // Throws rather than defaulting if the model has not loaded. See `calibration`.
  const cal = requireCalibration(calibration)
  const chars = Math.max(m.chars, m.words * 4)
  // No `??` and no default. A missing block count is a bug, not a case to guess at.
  if (!Number.isFinite(m.blocks) || m.blocks <= 0) {
    throw new Error(
      `section has no usable block count (${m.blocks}); the height estimate would be ` +
        'meaningless. This should be a type error, so it means the value came from ' +
        'storage or the wire rather than from a typed caller.',
    )
  }
  return cal.section_chrome_px + (chars / 100) * cal.px_per_100_chars + m.blocks * cal.px_per_paragraph
}

export const registry = new SectionRegistry({
  windowSize: 5,
  buildExtensions,

  onMount(editor: Editor, sectionId: string) {
    const slot = slotFor(sectionId)
    const dom = editor.view.dom as HTMLElement

    // Wrap the editor in the card the stylesheet describes.
    //
    // An earlier version appended the ProseMirror element straight into the slot,
    // which left the section with no `.section-slice` ancestor: no 46rem measure, no
    // 1.5rem padding, no 10px gap. The browser then wrapped at 1216px instead of
    // 736px and the section rendered 844px where the calibration had measured
    // 1527px. Every height the geometry held was for a document that did not exist,
    // and the estimate was 45% out.
    //
    // This is the same class of bug as `test/calibrate.ts` styling its own probe
    // instead of copying the app's CSS: measuring a different box than the one that
    // ships. The card is created here rather than reused from M3's `main.ts` so this
    // page has no dependency on the other surface's DOM.
    let card = slot.querySelector<HTMLElement>('.section-slice')
    if (!card) {
      card = document.createElement('div')
      card.className = 'section-slice'
      card.dataset.sectionId = sectionId
      slot.appendChild(card)
    }
    if (!card.contains(dom)) card.appendChild(dom)
  },

  onUnmount(sectionId: string) {
    // Empty the slot but leave the element in place for this tick. The scroller
    // prunes slot elements itself in `pruneSlots`, on the same reconciliation, so
    // that "mounted" and "present in the DOM" cannot disagree.
    //
    // Removing the element here instead would leave the scroller's slot lookup
    // returning null while it still believes the section is mounted, and the next
    // measurement pass would silently skip it.
    const slot = canvas.querySelector<HTMLElement>(`[data-section-id="${sectionId}"]`)
    if (slot) slot.innerHTML = ''
    // The card is created per mount, so it goes with the slot's contents.
  },

  isDirty: sectionId => editCommit?.isPending(sectionId) ?? false,

  /**
   * A section's bytes have been written, so `record.dirty` goes back to false.
   *
   * Called from `onBeforeUnmount`, which is where the host has just been handed the
   * snapshot to persist. Without it the flag is write-once — a section born from a split is
   * dirty forever, and `pruneSection` refuses it forever.
   */
  onPersisted: markPersisted,

  // What a departing section referenced. Read for diagnostics and preflights; *not* used to
  // release, because `AssetImage`'s NodeView owns that reference and the editor's destruction
  // already destroys the NodeView. See `registry.ts` for why two owners leaked.
  assetsOf: json => assetHashesIn(json),

  onChange(sectionId: string, _json: unknown, _metrics: SectionRecord['metrics']) {
    // Height changes are picked up by the ResizeObserver rather than by re-estimating
    // from metrics, because the DOM is authoritative about its own layout.
    //
    // The commit is *recorded*, not sent: `EditCommitter` coalesces a typing burst into
    // one write per window, and reading the editor at send time rather than now is what
    // makes it persist the state the user last had rather than the one they had when the
    // window opened.
    //
    // `localMetrics` is used for the mark count alone. Words, characters and blocks are
    // derived by Rust from the JSON it stores, and sending them would be sending numbers
    // that are either ignored or, worse, trusted.
    editCommit?.record(sectionId, () => {
      const editor = registry.editorIfMounted(sectionId)
      if (!editor) return null
      const current = editor.getJSON()
      return { json: current, markCount: localMetrics(current).marks }
    })
    void maybeSplitFocused()
  },

  onBeforeUnmount(sectionId, _snapshot, dirty) {
    // The zero-data-loss path, and the reason it is here rather than in `onUnmount`:
    // by the time `onUnmount` fires the only copy of the unsaved bytes has already been
    // handed over, and the editor is about to be destroyed. Getting them here means the
    // commit starts while the snapshot is still in hand.
    //
    // A clean section is left alone. Folding the WAL for every section a scroll passes
    // would put a write on the hot path for documents nobody is editing.
    if (!dirty) return
    void hydrator?.forget(sectionId)
    void editCommit?.flushNow(sectionId, booted?.payload.document_id)
  },

  onPrune(removedId, previousId) {
    // Fires *after* `registry.remove`, so `registry.ids()` is already the new ordering.
    // `reportPrune` re-keys the geometry from it synchronously and then tells the store.
    //
    // Not awaited, for the same reason as `onMerge` below: it crosses IPC, nothing
    // downstream depends on the round trip, and blocking a key handler on one would put
    // the store on the typing path, which is the thing the WAL exists to avoid.
    void reportPrune(removedId, previousId)
  },

  onMerge(sourceId, targetId) {
    // The editors have already been merged; Rust's copy has not. Reported
    // asynchronously because it crosses IPC, and deliberately not awaited — nothing
    // downstream depends on it, and blocking a key handler on a round trip would put
    // the store on the typing path, which is the thing the WAL exists to avoid.
    void reportBoundaryMerge(sourceId, targetId)
  },
})

/** The slot element for a section, created on first use. */
function slotFor(sectionId: string): HTMLElement {
  const index = sections.findIndex(s => s.id === sectionId)
  let el = canvas.querySelector<HTMLElement>(`[data-slot="${index}"]`)
  if (!el) {
    el = document.createElement('div')
    el.className = 'slot'
    el.dataset.slot = String(index)
    el.dataset.sectionId = sectionId
    canvas.appendChild(el)
  }
  return el
}

