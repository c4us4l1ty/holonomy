/** `File -> Optimize Document`. */
async function runOptimize(notice: HTMLElement | null): Promise<void> {
  try {
    const report = await optimizeDocument()
    if (!notice) return
    if (report.assetsDeleted === 0 && report.pagesReclaimed === 0) {
      // "Nothing to reclaim" is a legitimate answer, not a failure — a document nobody has
      // pruned images from is the common case and should read as information.
      notice.textContent = 'Nothing to reclaim'
      return
    }
    // Both numbers, because they answer different questions and only one is a promise
    // about data: `assetsFreed` is content removed, `pagesReclaimed` is space the file gave
    // back. An asset freed from the middle of a database is fully deleted and returns
    // nothing — see `optimize_document` for the measurement.
    const freed = formatBytes(report.assetsFreed)
    const pages = report.pagesReclaimed
    notice.textContent =
      pages > 0
        ? `Reclaimed ${freed} of orphaned images and ${pages} page${pages === 1 ? '' : 's'}`
        : `Reclaimed ${freed} of orphaned images (kept for reuse; run a backup to compact the file)`
  } catch (e) {
    if (notice) {
      notice.textContent = `Optimize failed: ${e instanceof Error ? e.message : String(e)}`
    }
  }
}

/** Human-readable bytes, because the report is shown to a person. */
function formatBytes(n: number): string {
  if (n < 1024) return `${n} B`
  const units = ['KB', 'MB', 'GB']
  let value = n / 1024
  let unit = 0
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024
    unit++
  }
  return `${value.toFixed(1)} ${units[unit]}`
}

