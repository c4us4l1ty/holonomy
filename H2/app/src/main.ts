/**
 * The fixture document the verification created, so it can be deleted again.
 *
 * Tracked rather than left to the caller, because the caller is `verify.ts` and it can
 * throw before its cleanup runs. The id is here so `dropFixture` works from a single
 * call, and the absence of one shows up as an undeleted `Verification fixture`
 * document rather than as silent accumulation.
 */
let fixtureDocumentId: string | null = null

const bridge: GeometryBridge = {
  totalHeight: () => geometry.totalHeight(),
  sectionAt: y => geometry.sectionAt(y),
  visibleRange: (y, h, o) => geometry.visibleRange(y, h, o),
  offsetOf: i => geometry.offsetOf(i),
  // Reports the compensation; it does not apply it. Ownership of the scroll
  // position belongs to the scroller, which funnels every correction through one
  // path so a section measured from two directions cannot be compensated twice.
  measure: (i, h, top) => geometry.measure(i, h, top),
}

/** Load a document and start scrolling.
 *
 * Awaits the calibration first, and refuses to build a geometry without it. That
 * ordering is the whole point of loading rather than hard-coding: a `LocalGeometry`
 * built from a guessed model would produce heights that disagree with every
 * measurement taken against the real one, and the disagreement would only show up
 * as a subtly wrong scrollbar.
 */
export async function load(
  next: SectionRecord[],
  payload?: BootPayload | null,
  options: { contentIsRecoverable?: boolean } = {},
): Promise<void> {
  // Whether eviction may drop a record's bytes. Read once, here, because it is a property
  // of the document being loaded and every consumer of it is inside this function.
  const contentIsRecoverable = options.contentIsRecoverable ?? false
  // The calibration must be loaded before any height is estimated, so a payload that
  // carries one is applied here rather than fetched later. See `loadCalibration`.
  if (!calibration) await loadCalibration(payload)

  scroller?.dispose()
  observer?.disconnect()
  mutationObserver?.disconnect()
  canvas.innerHTML = ''
  // One array of records, owned by the registry, and `sections` is a *reference* to it
  // rather than a parallel copy. `registry.load` used to shallow-copy every record, which
  // gave each section two objects: mutations through `registry.record(id)` — the cache's
  // eviction path writes `loaded` and `json` there — were invisible to the reads the
  // scroller's mount path makes here. The result was a section that was simultaneously
  // evicted and loaded, so scrolling back to it mounted an editor on the placeholder
  // instead of re-fetching. See `SectionRegistry.load`.
  sections = next
  registry.load(next)
  // The transport is passed in rather than defaulted, so the one place that knows a
  // height is going to Rust is here and not inside `height-sync.ts`. The default
  // there is a lazy import for tests that supply their own transport anyway.
  heightSync ??= new HeightSync({ send: updates => syncSectionHeights(updates) })
  editCommit ??= new EditCommitter({
    send: (sectionId, json, markCount) => commitSectionEdit(sectionId, json, markCount),
    flush: documentId => flushDocument(documentId),
  })

  geometry = new LocalGeometry(next.map(s => estimateHeight(s.metrics)))
  // Every height here is an estimate, so the identity mapping is exact: index i is
  // `next[i]`. This is the only place the two arrays are built together, which is why
  // it is also the only place the ids need recording.
  geometryIds = next.map(s => s.id)

  // A section's height changes without any scroll event when the user types, or
  // when an image decodes. This is the only thing that keeps the scrollbar honest
  // while they are not scrolling.
  observer = new ResizeObserver(entries => {
    let compensated = false
    for (const entry of entries) {
      const index = Number((entry.target as HTMLElement).dataset.slot)
      if (!Number.isFinite(index)) continue
      const height = entry.contentRect.height
      const result = geometry.measure(index, height, scrollerEl.scrollTop)
      // Accumulate rather than refreshing per entry: the observer fires with a
      // batch, and refreshing between entries would reconcile against a
      // half-updated geometry. Sum first, apply once.
      if (result.compensate !== 0) {
        compensationPending += result.compensate
        compensated = true
      }
      // Queued on this same task as the local update, and deliberately *not*
      // awaited: `geometry.measure` above has already made the compensation decision
      // from current heights, so nothing here is on the path to the next paint. The
      // queue collapses repeated measurements of one section and flushes at most
      // once per interval.
      const section = sections[index]
      if (section) heightSync?.record(index, section.id, height)
    }
    if (compensated) {
      scrollerEl.scrollTop += compensationPending
      compensationPending = 0
      void scroller?.refresh()
    }
  })

  mutationObserver = new MutationObserver(() => {
    for (const el of canvas.querySelectorAll<HTMLElement>('.slot')) observer?.observe(el)
  })
  mutationObserver.observe(canvas, { childList: true })

  // Seed the cache from the records, which are the content the caller supplied.
  //
  // Not from `booted.withContent`: a record's own `loaded` flag already says whether its
  // json is real, and reaching past it into the boot result meant the harness -- whose
  // records come from `loadSynthetic`, not from a boot payload -- looked like it had no
  // content anywhere. That broke every scroll test.
  cache.clear()
  cache.onEviction(id => {
    const record = registry.record(id)
    // Only blank a section that is not on screen. One in the buffer window is about to be
    // mounted, and blanking it would evict the very content the fetch guard protects.
    if (!record || bufferWindow.has(id)) return
    // Only blank when the bytes can actually be fetched again.
    //
    // The cache bound keeps renderer memory off document length, which only works if
    // dropping an entry drops the bytes. So the question is not "is there a bridge" but
    // "are these bytes in the store" -- and for a document the caller supplied, they are
    // not. `get_section` would report a section that does not exist, and the section
    // would be permanently un-mountable.
    //
    // This is not hypothetical: the in-engine verification loads a 120-section synthetic
    // document into a window that *does* have a bridge, so keying on the bridge alone
    // blanked sections 31 onwards and the run reported an 18-section window with heights
    // 56% out. Both were the cache destroying content it had no way to restore.
    if (contentIsRecoverable) {
      record.json = EMPTY_DOC
      record.loaded = false
    }
  })
  for (const record of next) {
    if (record.loaded) cache.set(record.id, record.json)
  }

  hydrator = new SectionHydrator({
    fetchSection: sectionId => getSection(sectionId, booted?.payload.document_id),
    cache,
    // The scroller's buffer window, which is the answer to "is this still wanted". A
    // section that has left it cannot be mounted, so holding its content would only leak
    // memory until the cache evicted it.
    isInWindow: sectionId => bufferWindow.has(sectionId),
    // Content arriving is what makes a section mountable, so the mount happens *here*
    // rather than at the call site that started the fetch.
    //
    // The call site cannot do it: `ensure` resolves with the content when the cache had
    // it and with `null` when it *started a fetch*, and the second case is the one that
    // needs a mount later. Branching on the resolution left every hydrated section
    // permanently un-mounted — an empty card where a section should be, for a document
    // the store had the content for the whole time. The in-engine check found it; no
    // unit test could, because the defect only exists once a real fetch resolves.
    onContent: (sectionId, json) => {
      mountHydrated(sectionId, json)
    },
    onError: (sectionId, error) => {
      console.error(`[hydrate] could not fetch section ${sectionId}`, error)
    },
  })

  scroller = new SectionScroller({
    container: scrollerEl,
    canvas,
    geometry: bridge,
    overscan: 1,
    strategy: 'absolute',

    mount(index) {
      const section = sections[index]
      if (!section) return null

      // A section with no content cannot be mounted. Mounting an editor on an empty doc
      // would be worse than not mounting: the first keystroke in it would overwrite the
      // stored section. So the fetch starts and the slot comes back empty, and the editor
      // appears when the content arrives.
      //
      // The gate is `record.loaded`, not cache residency. Those differ exactly when the
      // cache has evicted a section whose bytes were *not* dropped because there was no
      // bridge to fetch them from again -- and in that case the record still holds real
      // content and must still mount. Gating on residency made the browser harness
      // un-scrollable past thirty sections.
      //
      // The `void` is not fire-and-forget for its own sake: `ensure` resolves with the
      // content when it was resident, and with `null` when it started a fetch. It cannot
      // be awaited, because `mount` is called from the scroller's synchronous
      // reconciliation.
      if (!section.loaded) {
        void hydrator?.ensure(section.id)
        // Deliberately *not* observed. The slot exists so the window keeps a position,
        // but it holds no editor and so has no height worth reporting, and the observer is
        // the only thing that can shrink the geometry. `mountHydrated` observes the slot
        // once the editor exists, so the first measurement a section ever contributes is
        // of real content.
        //
        // # What this is worth, stated honestly
        //
        // When this run first failed, every section past the boot window reported its
        // empty height, the geometry collapsed towards zero and the document shrank to the
        // twelve sections that had loaded. That was a *consequence* of hydration failing,
        // not an independent defect, and the fix for hydration is what closed it.
        //
        // Restoring `observer.observe(slotFor(section.id))` here was tried as a mutation
        // and the in-engine run still reported 36/36. So no check distinguishes the two,
        // and this comment is not claiming one does. It stays because a fetch that fails
        // is reachable — a corrupt section, a store that is momentarily locked — and in
        // that case the difference between a transient zero and no measurement at all is
        // the difference between a document that recovers and a document whose scrollbar
        // no longer describes its contents.
        return slotFor(section.id)
      }

      // Idempotent: the registry returns the live editor if there is one, which
      // matters because focus may have already mounted it.
      registry.mount(section.id)
      const slot = slotFor(section.id)
      observer?.observe(slot)
      return slot
    },

    unmount(index) {
      const section = sections[index]
      if (!section) return
      // Stop observing the slot. Not `slotFor`: that would *create* the element
      // for a section on its way out, which is the opposite of unmounting it.
      const existing = canvas.querySelector<HTMLElement>(`[data-slot="${index}"]`)
      if (existing) observer?.unobserve(existing)
      registry.unmount(section.id)
    },

    pinnedIndex: null,

    onWindowChange(indices) {
      // The buffer window moved, so every outstanding content fetch is now potentially
      // stale. Bumping the generation is what makes a late response recognisable as
      // late -- without it, a fling's worth of responses would each apply to sections
      // that have long since left the window.
      hydrator?.newGeneration()
      syncBufferWindow(indices)
    },
  })

  scroller.start()
  void scroller.refresh()
}

/**
 * Record which sections are in the buffer window, and age the cache.
 *
 * # Why the window is a `Set` of ids
 *
 * The hydrator asks "is this section still wanted", not "is this index still in range".
 * A section's index moves whenever the ordering does — a split inserts one — so an index
 * range would answer about the wrong section after any structural change. Ids do not move.
 *
 * # Why the cache is touched here and not in `get`
 *
 * A section the scroller mounted is *used*, whether or not anything read it out of the
 * cache. Counting a mount as a cache hit would make the hit rate a measure of scrolling
 * rather than of the cache being right.
 */
/**
 * Mount a section whose content has just been fetched.
 *
 * # Why this exists rather than branching on `ensure`'s resolution
 *
 * Because `ensure` has two answers — "it was already resident, here it is" and "I have
 * started a fetch" — and the second is the one that needs a mount *later*, after the
 * round trip. Returning from the call site on `null` therefore stranded every hydrated
 * section: the content arrived, the record was marked loaded, and nothing ever built the
 * editor. The user saw an empty card in a document the store had the text for.
 *
 * The bug is invisible to a unit test because it needs a real fetch to resolve, which is
 * exactly what the in-engine verification exists to cover.
 *
 * Idempotent: `registry.mount` returns the live editor if there is one, so a window
 * change racing the fetch produces one editor rather than two.
 */
function mountHydrated(sectionId: string, json: unknown): void {
  const record = registry.record(sectionId)
  if (record) {
    record.json = json
    record.loaded = true
  }
  // Only if it is still wanted. A response that passed the hydrator's generation guard
  // and landed while the window moved again would mount a section nobody is looking at,
  // which costs a ProseMirror instance for nothing.
  if (!bufferWindow.has(sectionId)) return
  const slot = slotFor(sectionId)
  registry.mount(sectionId)
  observer?.observe(slot)
  void scroller?.refresh()
}

function syncBufferWindow(indices: number[] = scroller?.mountedIndices() ?? []): void {
  bufferWindow.clear()
  for (const index of indices) {
    const section = sections[index]
    if (section) bufferWindow.add(section.id)
  }
  for (const id of cache.residentIds()) {
    if (bufferWindow.has(id)) cache.touch(id)
  }
}

// -- boot ------------------------------------------------------------------

/**
 * Boot: fetch the payload, hydrate the geometry, mount the visible window.
 *
 * # The four steps, and why they are in this order
 *
 * 1. **Calibration.** Before anything that estimates a height, because a geometry
 *    built from a guessed model disagrees with every measurement taken against the
 *    real one and the only symptom is a subtly wrong scrollbar. The boot payload
 *    carries the calibration, so under Tauri nothing is fetched at all.
 * 2. **Records.** Manifest rows become `SectionRecord`s with their content, which is
 *    decompressed here. `document-boot.ts` owns that; this step is only about having
 *    them.
 * 3. **Geometry.** Seeded from the manifest's counts, so the scrollbar is correct for
 *    sections that have never been rendered — which for a 2000-page document is
 *    nearly all of them.
 * 4. **Mount.** `load` starts the scroller, which mounts the window around the saved
 *    position (or the top).
 *
 * # What this deliberately does not do
 *
 * It does not fetch content for sections beyond the boot window, because no command
 * exists to ask for it. `BootResult.withContent` records which sections actually have
 * their content, and `sectionsWithoutContent` reports the rest so the status bar can
 * say so — a document longer than the boot window is scrollable but not editable
 * past its end, and mounting an empty editor there would destroy the stored section
 * on its first keystroke.
 */
export async function boot(options: { documentId?: string } = {}): Promise<BootResult> {
  // 1. A payload fetch is also how the calibration arrives, so this is one round trip
  //    rather than two.
  const result = hasBridgeShape()
    ? await bootDocument({ ...options, fetchPayload: id => getDocumentBoot(id) })
    : await (async () => {
        await loadCalibration(null)
        return bootDocument(options)
      })()

  booted = result
  // 2 & 3 & 4. `load` seeds the geometry from `records` and mounts the window; it
  // needs the payload only for the calibration, which it has already been given.
  //
  // `contentIsRecoverable` is true only for a document that came out of the store, which
  // is what tells the cache whether it may drop bytes. See `onEviction` above.
  await load(result.records, result.payload, { contentIsRecoverable: result.source === 'bridge' })
  return result
}

/** Whether a Tauri host is present, without importing the bridge's internals. */
function hasBridgeShape(): boolean {
  return typeof (globalThis as any).__TAURI__?.core?.invoke === 'function'
}

/** Sections whose manifest row arrived but whose content did not. */
export function sectionsWithoutContent(): string[] {
  if (!booted) return []
  return booted.records.filter(r => !booted!.withContent.has(r.id)).map(r => r.id)
}

/** The boot result, or null before boot has finished. */
export function bootState(): { source: string; sections: number; withContent: number } | null {
  if (!booted) return null
  return {
    source: booted.source,
    sections: booted.records.length,
    withContent: booted.withContent.size,
  }
}

// -- lifecycle -------------------------------------------------------------

/**
 * Where a caret is now, expressed so it survives a split.
 *
 * Read from the live editor rather than from the stored JSON, because the live editor
 * is the only one that has the unsaved keystrokes.
 */
function currentAnchor(): CaretAnchor | null {
  const id = registry.focused
  if (!id) return null
  const editor = registry.editorIfMounted(id)
  if (!editor) return null
  return { sectionId: id, offset: caretOffsetFromStart(editor.state.doc, editor.state.selection.from) }
}

/**
 * Restore a caret anchor after a structural change.
 *
 * # Why this must not steal focus
 *
 * The user is typing. A split that moved focus to the new section, or that left it
 * nowhere, would be indistinguishable from the editor crashing — and the split is
 * something the user never asked for. So focus only moves if the section the caret
 * was in no longer exists, which after a merge is the one case where it must.
 *
 * The offset is re-resolved against whichever section now contains that text: for a
 * split, the anchor's own section if it survived, and for a merge, the section the
 * content was folded into.
 */
function restoreAnchor(anchor: CaretAnchor, survivingId: string): boolean {
  const target = registry.record(survivingId)
  if (!target) return false
  const editor = registry.mount(survivingId)
  if (!editor) return false

  // The offset was captured before the structural change, so it refers to the
  // pre-split text. `positionFromCaretOffset` is the inverse of the function that
  // captured it, and the two live in the same module so `test/lifecycle.ts` can
  // assert the round trip rather than assume it.
  const pos = positionFromCaretOffset(editor.state.doc, anchor.offset)
  editor.commands.setTextSelection(pos)
  if (registry.focused !== survivingId) registry.focus(survivingId)
  editor.commands.focus()
  return true
}

/**
 * Send a lifecycle action to Rust.
 *
 * A thin wrapper so the coordinator has one place to change if the transport does.
 * Under a browser there is no Rust, so the split and merge are applied locally and
 * reported as unapplied rather than throwing: the harness exercises the geometry and
 * the editors, and pretending the store said yes would be a lie the harness would
 * then assert against.
 */
/**
 * A test-supplied replacement for the lifecycle bridge.
 *
 * `null` means "no override", which is the production state. Set, it lets a browser suite
 * drive the *real* `applySplit`/`applyMerge` rather than hand-building the result — the
 * difference matters because `test/scroll.ts` had to split by hand, and a hand-built split
 * exercises the seam rule but not the reconciliation: the caret anchor, the registry insert,
 * and the geometry re-key together, which is the thing most likely to be wrong.
 *
 * Shaped like `setEditTransport`, which already exists for the same reason.
 */
let lifecycleTransport:
  | ((action: Parameters<typeof commitSectionLifecycle>[0]) => Promise<{ applied: boolean; section_ids: string[]; reason: string | null }>)
  | null = null

async function commitLifecycle(action: Parameters<typeof commitSectionLifecycle>[0]) {
  if (lifecycleTransport) return lifecycleTransport(action)
  if (!hasBridgeShape()) {
    return { applied: false, section_ids: [], reason: 'no bridge: browser harness' }
  }
  return commitSectionLifecycle(action)
}

/** The `LifecycleHost` the coordinator drives. */
const lifecycleHost: LifecycleHost = {
  registry,
  sectionIds: () => registry.ids(),
  commit: action => commitLifecycle(action),
  reindex(ids, change) {
    // The section count changed, so every offset after the change point moved. The
    // heights themselves are still correct — they are properties of sections, not of
    // positions — so they are re-keyed by identity rather than re-estimated. Dropping
    // them would send the whole document back to estimates and the scrollbar would
    // visibly lurch.
    //
    // The arithmetic, and the positional bug this replaced, are in `core/rekey.ts`.
    geometry = new LocalGeometry(
      rekeyHeights({
        previousIds: geometryIds,
        previousHeights: geometry.snapshotHeights(),
        newIds: ids,
        change,
        // A section with no measurement and no allocation has never been on screen.
        // The metrics estimate is right for it — the same model the whole document
        // booted on — and `estimateHeight` throws rather than guessing if the block
        // count is missing, which is the correct place for that failure.
        estimate: id => {
          const record = registry.record(id)
          return record ? estimateHeight(record.metrics) : 0
        },
      }),
    )
    geometryIds = [...ids]
    rebuildSlots(ids)
  },
  onApplied(_result, anchor) {
    // Focus moves only if the section the caret was in no longer exists — which is
    // the merge case. After a split it always survives, so focus stays exactly where
    // the user left it.
    const surviving = registry.record(anchor.sectionId) ? anchor.sectionId : registry.ids()[0]!
    restoreAnchor(anchor, surviving)
  },
}

/**
 * Rebuild the slot elements after the ordering changed.
 *
 * Slots are keyed by index, so a split shifts every index after the cut. Re-creating
 * them is the only way to stop a section's slot pointing at another section's
 * position — which would place one section's content at another section's offset,
 * and the first measurement would then be measured against the wrong place.
 */
function rebuildSlots(ids: string[]): void {
  observer?.disconnect()
  canvas.innerHTML = ''
  for (let i = 0; i < ids.length; i++) {
    const el = document.createElement('div')
    el.className = 'slot'
    el.dataset.slot = String(i)
    el.dataset.sectionId = ids[i]!
    canvas.appendChild(el)
  }
  for (const el of canvas.querySelectorAll<HTMLElement>('.slot')) observer?.observe(el)
}

/**
 * Split the focused section if it has outgrown a limit.
 *
 * Called after a keystroke, not before: a split is a structural change and should not
 * happen in the middle of a typing burst. The anchor is taken *before* the request so
 * it refers to the pre-split document, which is the only document whose offsets are
 * known.
 */
export async function maybeSplitFocused(): Promise<boolean> {
  const id = registry.focused
  if (!id) return false
  return maybeSplitSection(id)
}

/**
 * Run the split trigger against one named section.
 *
 * Split out from [`maybeSplitFocused`] so the two share an implementation rather than
 * merely agreeing today: the keystroke path passes the focused section, and
 * `test/oscillation.ts` passes an explicit id to drive a specific one. A second copy would
 * be a second place for the split rules to diverge.
 */
export async function maybeSplitSection(id: string): Promise<boolean> {
  const editor = registry.editorIfMounted(id)
  if (!editor) return false

  const record = registry.record(id)
  if (!record) return false
  // Only `words` and `marks` are recomputed. `chars` and `blocks` stay as the store
  // wrote them, because `analyze` in Rust is the definition of those and the height
  // model is calibrated against them; a second frontend estimate would be a second
  // model. See `splitMetricsOf`.
  const live = localMetrics(editor.getJSON())
  if (!splitTrigger(live)) return false
  // Only `words` and `marks` are written back. `chars` and `blocks` stay as the store
  // left them, because `analyze` is the definition of those and the height model is
  // calibrated against them; overwriting them with a local estimate each keystroke
  // would mean the scrollbar tracked an estimate rather than the model. See
  // `localMetrics`.
  record.metrics = { ...record.metrics, words: live.words, marks: live.marks }

  const anchor = currentAnchor()
  const result = await applySplit(lifecycleHost, id, editor.getJSON(), anchor ?? { sectionId: id, offset: 0 })
  return result.applied
}

/**
 * Report a pruned empty section to Rust, and re-key the geometry once it has gone.
 *
 * The frontend has already removed the section from the registry — `registry.pruneSection`
 * does that before it calls `onPrune`, because it has to unmount the editor and the
 * section's bytes have to be gone from the renderer's view before the store is told.
 *
 * # Why the geometry waits for the round trip
 *
 * `reindex` needs the *new* ordering to re-key heights against section identity. That
 * ordering arrives in the `LifecycleResult`, because the store returns the whole
 * `section_ids` array rather than a diff. Fabricating the new ordering here by splicing
 * the removed id out of the current one would be guessing at exactly the thing the store
 * is being asked to confirm, and a guess that is wrong mis-positions every section below.
 *
 * The window where the geometry still has N entries for an N−1 section document is one
 * IPC round trip on a keystroke that already sat on a seam — rare, and the scroller
 * re-reconciles against the correct geometry the moment the reply lands.
 */
async function reportPrune(removedId: string, previousId: string): Promise<boolean> {
  // Re-key the geometry *now*, from the ordering the registry already has, before the
  // round trip. The section has already been removed from the registry by the time this
  // runs, so `ids()` is the new ordering and re-keying now costs nothing — whereas waiting
  // for the reply left the geometry sized for one section too many, with every section
  // below the seam offset by a row, and unrecoverable when there is no store to answer.
  //
  // The reply's `section_ids` still overwrites this when it arrives, so the store remains
  // authoritative; this is only about not being visibly wrong in between.
  //
  // The change is described as a `merge` because that is what the geometry arithmetic
  // needs: the removed section's measured height is added to its predecessor rather than
  // discarded, which is what keeps the document's total height — and so the scroll
  // position — unchanged by the removal. The two differ only in what the *store* does:
  // a merge re-bodies the target, a prune deletes a row, and `onPrune` sends `prune`.
  lifecycleHost.reindex(registry.ids(), { kind: 'merge', intoSectionId: previousId, removedId })

  const index = booted?.payload.document_id ? registry.ids().indexOf(previousId) + 1 : 0
  try {
    const result = await lifecycleHost.commit({
      kind: 'prune',
      section_id: removedId,
      previous_section_id: previousId,
      index,
    })
    if (result.applied) {
      // The store's ordering is authoritative; adopt it in case it differs from ours.
      lifecycleHost.reindex(result.section_ids)
      return true
    }
    return false
  } catch (e: any) {
    // The section is already gone from the registry, so a failure here leaves the
    // renderer and the store disagreeing about the document's shape. Nothing is lost —
    // the section was empty — but the geometry cannot be re-keyed from a reply that
    // never came. Report it rather than leaving a silent divergence.
    console.error('[holonomy] prune of an empty section failed to reach the store', e)
    return false
  }
}

/** Report a boundary merge to Rust, after the frontend has performed it. */
export async function reportBoundaryMerge(sourceId: string, targetId: string): Promise<boolean> {
  const anchor = currentAnchor() ?? { sectionId: targetId, offset: 0 }
  // `applyMerge` resolves the anchor into the target itself, so there is no second
  // restore here to get out of step with the first.
  const result = await applyMerge(lifecycleHost, sourceId, targetId, anchor)
  return result.applied
}

/** Report a successful mount to the shell, and record which engine mounted us.
 *
 * Under Tauri, the shell needs to know the frontend came up: a blank window and a
 * slow boot look identical from outside. Under the browser harness there is no
 * shell, so this records locally instead.
 *
 * The engine name comes from the shell rather than from user-agent sniffing. A
 * UA string is a proxy for the engine and webkit2gtk's is unreliable for exactly
 * the cases that matter; the shell knows because it linked against it.
 */
async function reportMount(): Promise<{ engine: string | null; version: string | null }> {
  try {
    const identity = await identifyEngine()
    if (identity.engine) await reportMounted()
    return identity
  } catch (e) {
    // A failed report must not take the app down. The editor is usable; the shell
    // simply will not have an engine attribution for this run, and the
    // cross-engine harness is meant to fail on a missing attribution.
    console.error('[holonomy] mount report failed', e)
    return { engine: null, version: null }
  }
}

