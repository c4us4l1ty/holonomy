/**
 * The height model, loaded rather than written here. See the module header.
 *
 * Null until [`loadCalibration`] completes. Anything needing it before then is a
 * boot-ordering bug and throws rather than guessing, because guessing means a
 * default that disagrees with the model every estimate was fitted against.
 */
let calibration: GeometryCalibration | null = null

/**
 * Load the height model.
 *
 * # Order matters, and the boot payload wins
 *
 * Under Tauri the boot payload carries the calibration, so it is authoritative and
 * nothing is fetched. In a browser there is no boot payload, so the generated
 * artifact is read.
 *
 * That ordering is the whole point of shipping the calibration in the payload rather
 * than compiling it into the frontend: a packaged app cannot end up disagreeing with
 * the model its own estimates are measured against. `setHarnessCalibration` hands the
 * same value to the browser fallback in `document-boot.ts`, so the fallback's
 * geometry is built from the identical numbers rather than a second copy.
 */
async function loadCalibration(payload?: BootPayload | null): Promise<void> {
  if (payload) {
    calibration = payload.calibration
    setHarnessCalibration(payload.calibration)
    return
  }
  const res = await fetch('/calibration.json')
  if (!res.ok) {
    throw new Error(
      `calibration.json is missing (HTTP ${res.status}). Generate it with:\n` +
        `  cargo run --release --bin emit-calibration > app/public/calibration.json`,
    )
  }
  calibration = (await res.json()) as GeometryCalibration
  setHarnessCalibration(calibration)
}

/**
 * The extensions every section editor is built from.
 *
 * # Why equations are in the list and not enabled per document
 *
 * Because the seam rule reads `ATOMIC_BLOCK_TYPES` from raw JSON, and a node type the
 * editor installs but the seam rule does not know about is a block the splitter will happily
 * cut in front of and the merger will then refuse to move across. `test/scroll.ts` compares
 * the two against the *installed* schema rather than a fixture, so adding a node here
 * without listing it there fails the suite.
 *
 * # Why `mathBlock` and `inlineMath` are two nodes and not one with a flag
 *
 * See `core/math.ts`: the JSON says which it is, so a round trip does not have to infer it
 * from context, and a parser cannot guess wrong and turn a display equation into running
 * text.
 */
function buildExtensions(): unknown[] {
  return [
    StarterKit.configure({ undoRedo: false }),
    Table,
    TableRow,
    TableCell,
    TableHeader,
    InlineMath,
    BlockMath,
    // `host` is supplied per call rather than captured, so the resolver the NodeView uses is
    // the one this session owns. See `core/image.ts` for why acquiring happens there and
    // releasing happens in the registry's unmount path.
    AssetImage.configure({ host: assetHost }),
  ]
}

