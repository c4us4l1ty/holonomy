/**
 * The shortcut registry and the toolbar, wired to the focused section.
 *
 * # Why undo and redo are global while formatting is not
 *
 * A document is many Tiptap editors — one per mounted section — and each has its own history. So
 * a per-editor undo would step back through *one section* while the user believes they are
 * stepping back through their document, and pressing it four times to cross a section boundary is
 * indistinguishable from it being broken. `UndoCoordinator` (M3) is the document-wide stack, so
 * `undo`/`redo` are registered as **global** commands and formatting as **editor** ones: a bold
 * applies where the caret is, and an undo applies to the document.
 *
 * # Why the toolbar reflects the focused editor rather than the mounted set
 *
 * Because there is no such thing as "the document's bold". A toolbar showing the union of every
 * mounted section's state would be bold whenever *any* section is bold, which is a lie about
 * every other section. So it follows focus, and a section with no focus shows nothing active.
 *
 * # Why an unavailable command renders disabled rather than hidden
 *
 * Because the toolbar changing shape between sections reads as a bug. An equation command absent
 * from this section's schema should say "not available here", which is a statement, rather than
 * make the whole bar reflow.
 */
/** The editor the toolbar and the editor-scoped shortcuts act on. */
function focusedEditor(): EditorLike | null {
  const id = registry.focused
  if (!id) return null
  return (registry.editorIfMounted(id) as unknown as EditorLike) ?? null
}

/**
 * Toolbar items keyed by the shortcut command that triggers them.
 *
 * # Why the toolbar is the source of truth
 *
 * Because the two must agree: `TOOLBAR_ITEMS` says `heading1` is `setHeading` with `{level: 1}`,
 * and the shortcut table says `heading1` is `mod+alt+1`. A second hand-written map from command to
 * Tiptap call would be a third place the three could disagree, and the disagreement would be a
 * chord that resolves and then does nothing.
 *
 * So the handlers are *derived* from the items and this lookup is the only one. A formatting chord
 * the item list does not describe is left unbound, which `unbound()` reports in a test rather than
 * the chord failing quietly in the product.
 */
const itemByShortcut = new Map(
  TOOLBAR_ITEMS.filter(item => item.shortcut).map(item => [item.shortcut as string, item]),
)

const shortcutRegistry = new ShortcutRegistry(
  {
    // Every editor command routes to the focused section's editor, derived from the item list so
    // a new item with a binding needs no second edit.
    ...Object.fromEntries(
      EDITOR_BINDINGS.map(binding => [
        binding.command,
        () => {
          const editor = focusedEditor()
          const item = itemByShortcut.get(binding.command)
          if (editor && item) runItem(editor, item)
        },
      ]),
    ),

    // The coordinator lives on the registry, not here: it needs the registry's
    // `resolveEditor` to reach a section that has scrolled out of the window, and history that
    // cannot reach an unmounted section is history that stops at the viewport.
    //
    // A null result means the stack is empty, which is not an error -- pressing undo with nothing
    // to undo should do nothing rather than report a failure.
    undo: () => {
      void registry.undo.undo()
    },
    redo: () => {
      void registry.undo.redo()
    },
    'app.save': () => {
      // "Save" is "flush now", not "write the document". Every mounted section's pending edit is
      // already batched into `commit_section_edit`, so a save is a flush of that queue and
      // nothing more -- there is no separate document-level write to do.
      for (const id of registry.ids()) {
        if (registry.editorIfMounted(id)) void editCommit?.flushNow(id)
      }
    },
    'app.exportPdf': () => {
      void (globalThis as any).HOLO_SCROLL?.exportWithPanel?.()
    },
    'app.search': () => {
      void (globalThis as any).HOLO_SCROLL?.openSearch?.()
    },
  },
  { navigator: typeof navigator === 'undefined' ? null : navigator },
)

/**
 * Run a toolbar item's command against the focused editor.
 *
 * `runItem` rather than calling `chain()` directly, because `runItem` is where the *item* is
 * consulted: it knows whether the editor supports the command, what arguments the item carries,
 * and whether the item needs a value first. A toolbar that called the editor directly would
 * offer a command the schema does not have and get a silent no-op.
 */
function runToolbarCommand(_command: string, _args: readonly unknown[], item: ToolbarItem): void {
  const editor = focusedEditor()
  if (!editor) return
  // `runItem` takes the *item*, not the command, because the item is where the arguments and the
  // "needs a value first" flag live. A toolbar that called the editor directly would offer a
  // command the section's schema does not have and get a silent no-op.
  runItem(editor, item)
}

/** Mount the toolbar and keep it in step with focus and selection. */
function mountToolbar(): void {
  const host = document.getElementById('toolbar-host')
  if (!host) return
  const root = renderToolbar(toolbarState(focusedEditor()), { run: runToolbarCommand })
  host.replaceChildren(root)

  // Updated on every editor transaction rather than on a `selectionUpdate` event, because a
  // mark that arrives from a *remote* edit (M6 sync) also changes what the toolbar should show,
  // and `selectionUpdate` does not fire for one.
  document.addEventListener('selectionchange', () => {
    updateToolbar(root, toolbarState(focusedEditor()))
  })
  for (const id of ['mousedown', 'keyup', 'focusin']) {
    document.addEventListener(id, () => updateToolbar(root, toolbarState(focusedEditor())), true)
  }

  // The shortcut listener is on `document` in the capture phase so a chord is seen before a
  // section editor's own handler can `stopPropagation` it — which one of them does, for its own
  // internal bindings. Without capture, `mod+z` would reach whichever editor the caret is in
  // before the document-wide stack ever saw it.
  document.addEventListener(
    'keydown',
    event => {
      // `contextForElement` decides whether the event was inside a section editor or inside a
      // text field, rather than the caller re-deriving it. One definition of "is this a command
      // or is this someone typing" — and getting it wrong is how a shortcut eats the letter `b`.
      // `dispatch` *reports* that a chord matched; it does not consume the event. Consuming is
      // the caller's job, and the first version of this omitted it -- so `Ctrl+B` was resolved,
      // the handler ran, and the key event then carried on to Tiptap, which applied bold itself.
      //
      // That works by accident for formatting, and does not work at all for undo: the browser's
      // own `Ctrl+Z` and the registry's both ran, so the two fought. And nothing was actually
      // consumed, so `defaultPrevented` stayed false and a browser test could not tell a working
      // shortcut from a coincidental one.
      const outcome = shortcutRegistry.dispatch(event, contextForElement(event.target as Element | null))
      if (outcome.handled) consumeEvent(event)
    },
    true,
  )
}

/**
 * Ingest one image and insert it into `editor`.
 *
 * Named rather than inlined twice, because the paste path and the drop path must insert
 * identically: a figure that arrives by drop and one that arrives by paste are the same figure,
 * and a difference between the two paths is a bug a user would report as "sometimes pasting
 * images does nothing".
 *
 * The insert goes through `insertContent` rather than a raw transaction so it lands in the
 * editor's history. A pasted figure must be undoable with one Ctrl-Z like any other edit; a
 * transaction bypassing the history would leave the user unable to remove it.
 */
/**
 * The shape of the Tiptap commands this module uses.
 *
 * Declared rather than imported, because `main.ts` is wired against a *test* surface that hands
 * it plain objects as well as against real editors. Naming the three calls it needs is narrower
 * than importing the whole `Editor` type and does not force the test surface to be an editor.
 */
interface Insertable {
  commands: { insertContent(node: unknown): unknown }
  state: {
    doc: {
      descendants(
        visit: (node: { type: { name: string }; attrs: Record<string, unknown> }) => void,
      ): void
    }
  }
}

/** Whether an `image` node addressed by `src` is in the editor's document. */
function containsAsset(editor: unknown, src: string): boolean {
  const doc = (editor as Insertable).state.doc
  let found = false
  doc.descendants(node => {
    if (node.type.name === 'image' && node.attrs.src === src) found = true
  })
  return found
}

/**
 * Store one image and put it in the document.
 *
 * # Why `commands.insertContent` and not `chain().focus().insertContent`
 *
 * Because `chain().focus().insertContent(node)` inserts **nothing**, silently, when the caret is
 * at position 1 — and the status bar then says a figure was inserted. Measured in the browser on
 * a real focused section: `chain().focus().insertContent` left the document at 2524 nodes with
 * zero image nodes, while `commands.insertContent` inserted one. The `focus()` is what breaks it,
 * and the reason it was there — "the editor may not have focus" — is already false for a paste
 * or a drop, which are delivered to it.
 *
 * # Why the insert is verified rather than assumed
 *
 * Because "stored" and "in the document" are different claims and the user only sees one of
 * them. `ingestImage` returning a hash proves the bytes are in SQLite; it says nothing about the
 * node landing. So the caller reads the document back, and an image that did not arrive is
 * reported as one that did not.
 */
async function ingestBlobInto(
  file: Blob,
  editor: unknown,
): Promise<{ hash: string; width: number | null; height: number | null; inserted: boolean }> {
  const image = await ingestImage(file, { put: (bytes, mime) => putAsset(bytes, mime) })
  let inserted = false
  if (editor) {
    ;(editor as Insertable).commands.insertContent(image.node)
    inserted = containsAsset(editor, assetUrl(image.hash))
  }
  return { hash: image.hash, width: image.width, height: image.height, inserted }
}

/**
 * Attach the paste and drop handlers to the scroller, and report what was ingested.
 *
 * On the scroller rather than on `document`, so a drop anywhere in the window that is not the
 * document is *not* an insert. The alternative — a document-level handler with a hit test — is
 * the shape that ends up inserting a figure when the user drops a file on the status bar.
 *
 * Returns a handle rather than attaching and returning nothing, because a handler that cannot
 * be removed is a handler that survives the surface it was attached for, and this one is
 * attached to the live application page.
 */
function attachImageIngestion(onIngested: (results: IngestOutcome[]) => void): { detach(): void } {
  const detach = onImageDrop(
    document.getElementById('scroller') ?? document.body,
    async files => {
      const ingested: IngestOutcome[] = []
      for (const file of files) {
        // `focusedEditor()`, not the registry's raw field. `registry.focused` is a section *id*;
        // the version this replaces called it, which is a `TypeError` on every paste whenever a
        // section was focused, and nothing noticed because no test ran this code.
        const editor = focusedEditor()
        try {
          ingested.push(await ingestBlobInto(file, editor))
        } catch (e) {
          // A rejected figure is reported, not swallowed: the alternative is a paste that
          // appears to do nothing, which is indistinguishable from a broken paste handler.
          ingested.push({
            failed: file.name,
            reason: e instanceof IngestError ? e.reason : 'unknown',
            message: e instanceof Error ? e.message : String(e),
          })
        }
      }
      onIngested(ingested)
    },
  )
  return { detach }
}

/** One pasted or dropped image: inserted, or refused with a reason. */
type IngestOutcome =
  | { hash: string; width: number | null; height: number | null; inserted: boolean }
  | { failed: string; reason: string; message: string }

/** Narrows the union in place. A negative `!wasRefused(r)` does not narrow in TypeScript, so
 * both branches get a guard rather than one guard and two casts. */
function wasRefused(r: IngestOutcome): r is { failed: string; reason: string; message: string } {
  return 'failed' in r
}

function wasInserted(
  r: IngestOutcome,
): r is { hash: string; width: number | null; height: number | null; inserted: boolean } {
  return 'hash' in r
}

/** Show what a paste or drop did, in one line, replacing whatever was there. */
function reportIngested(results: IngestOutcome[]): void {
  const el = document.getElementById('ingest-report')
  if (!el || results.length === 0) return
  const refused = results.filter(wasRefused)
  const stored = results.filter(wasInserted)
  const parts: string[] = []
  // "stored" and "inserted" are counted separately, and deliberately. The bytes are in SQLite
  // either way; whether a node reached the document is a separate fact, and reporting the first
  // as the second is how a paste silently does nothing while claiming it worked.
  const landed = stored.filter(r => r.inserted)
  const orphaned = stored.filter(r => !r.inserted)
  if (landed.length) {
    const nouns = landed.length === 1 ? 'image' : 'images'
    // Dimensions go in only when every one of them was measurable. A malformed header yields
    // null, and a line reading "3×?" beside a figure that is perfectly fine is worse than no
    // number at all.
    const measured = landed.every(r => r.width !== null && r.height !== null)
    parts.push(
      measured
        ? `inserted ${landed.length} ${nouns} (${landed.map(r => `${r.width}×${r.height}`).join(', ')})`
        : `inserted ${landed.length} ${nouns}`,
    )
  }
  for (const r of refused) parts.push(`refused ${r.failed}: ${r.reason}`)
  if (orphaned.length) {
    const nouns = orphaned.length === 1 ? 'image is' : 'images are'
    parts.push(`${nouns} stored but no section had the caret, so nothing was placed`)
  }
  el.textContent = parts.join(' · ')
  el.classList.toggle('failed', refused.length > 0 || orphaned.length > 0)
  el.hidden = false
}

