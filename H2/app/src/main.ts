/**
 * Asset URLs, resolved once per session.
 *
 * `Image` is not constructible in Node, so `AssetResolver` lives here where a window
 * exists. See `core/assets.ts` for why it probes a transport rather than assuming one.
 */
/**
 * Where the resolver gets asset bytes, swappable for the browser harness.
 *
 * A `let` rather than a constant because the browser suite has no bridge: `get_asset` throws
 * "no Tauri host" there, and every asset test would fail for a reason that has nothing to do
 * with what it is testing. Swapping the *source* rather than the resolver keeps the refcount,
 * the caching and the revocation policy under test — which is the part worth testing — and
 * only replaces the fetch, which is not.
 */
let assetSource: (hash: string) => Promise<{ mime: string; bytes: Uint8Array }> = async hash => {
  const { mime, bytes } = await getAssetBytes(hash)
  // `number[]` off the wire becomes a `Uint8Array` here, once. The resolver should not have to
  // know that a number array was ever involved -- `geometry-bridge.ts` is where the wire shape
  // belongs, and this is the boundary that converts it.
  return { mime, bytes: Uint8Array.from(bytes) }
}

