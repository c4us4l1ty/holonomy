/**
 * The application. Scroll-driven mounting, wired to the section registry and,
 * since M5, to the bridge.
 *
 * # Why this file was called `scroller-app.ts`
 *
 * Because `main.ts` was taken by the M3 harness, which is a separate page
 * (`m3.html`) with a synthetic document and its own test surface. That was a
 * naming accident with teeth: "the main file" was a harness, and the file that
 * actually ships was the one with the qualified name. `index.html` loads this one
 * and a packaged build contains only this one, so it is the application; the M3
 * page moved to `m3-harness.ts`.
 *
 * The division of labour with the harness is unchanged and deliberate: the
 * registry owns section lifecycle and the editors, and both surfaces drive it.
 *
 * The division of labour matters and is easy to get backwards:
 *
 * - the **registry** knows what a section is and owns the editors. It mounts on
 *   *focus*, because a caret moving between sections must bring them with it.
 * - the **scroller** knows where the viewport is and decides what to mount on
 *   *scroll*. It does not know about editors, only that mounting produces an
 *   element it can measure.
 *
 * Both can mount the same section, and they must agree: `mount` is idempotent in
 * the registry, and the scroller's `unmount` is routed through it, so a section
 * the user is editing is never torn out from under the caret. The registry's
 * `pinnedIndex` is what enforces that.
 *
 * # On the height constants
 *
 * They are not written here. They come from the boot payload in the packaged app,
 * and from `public/calibration.json` — generated by `cargo run --bin
 * emit-calibration` — in the browser harness.
 *
 * They were previously hand-copied from `GeometryCalibration::default` in Rust
 * with a test asserting the copies matched. The test worked and the arrangement
 * was still wrong: two hand-maintained numbers that must agree, where the failure
 * mode is a silently stale comparison rather than a visible error.
 *
 * A stale artifact cannot now pass quietly, because the scroll suite bounds the
 * mean predicted-vs-measured error against real rendered sections. That checks the
 * consequence, which is strictly better than checking that two literals are equal.
 */

