//! Bidirectional paragraph resolution and per-line visual reordering (UAX #9, AUDIT OQ-11).
//!
//! `cluster` decides *where* grapheme boundaries sit; this module decides *in what horizontal
//! order* a wrapped line's clusters paint, while keeping L-8's single-geometry bijection intact:
//!
//! 1. Paragraph embedding levels (`P2–P3`), explicit embeddings/overrides/isolates (`X1–X10`,
//!    `MAX_DEPTH = 125`), weak types (`W1–W7`), paired brackets and neutrals (`N0–N2`,
//!    `MAX_PAIRING_DEPTH = 63`), and implicit levels (`I1–I2`, `L1`) are resolved per paragraph
//!    over UCD 18.0.0 property tables ([`tables`], generated by `scripts/gen-bidi-tables.py`).
//! 2. Greedy cluster line-wrapping runs in logical order first, because UAX #9 §3.4 breaks lines
//!    before reordering and cluster advances commute under permutation.
//! 3. Each wrapped line resets trailing whitespace and isolate controls (`L1.4`) to the paragraph
//!    embedding level and reverses maximal runs from the highest level down to the lowest odd
//!    level (`L2`).

mod tables;

/// Maximum explicit directional embedding/isolate depth permitted by UAX #9 (`BD2`).
const MAX_DEPTH: u8 = 125;

/// Maximum paired-bracket stack depth permitted by UAX #9 (`BD16`).
const MAX_PAIRING_DEPTH: usize = 63;

/// The UAX #9 `Bidi_Class` property values.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum BidiClass {
    L,
    R,
    Al,
    En,
    Es,
    Et,
    An,
    Cs,
    Nsm,
    Bn,
    B,
    S,
    Ws,
    On,
    Lre,
    Lro,
    Rle,
    Rlo,
    Pdf,
    Lri,
    Rli,
    Fsi,
    Pdi,
}

impl BidiClass {
    fn is_isolate_initiator(self) -> bool {
        matches!(self, Self::Lri | Self::Rli | Self::Fsi)
    }

    fn is_removed_x9(self) -> bool {
        matches!(
            self,
            Self::Rle | Self::Lre | Self::Rlo | Self::Lro | Self::Pdf | Self::Bn
        )
    }

    fn is_neutral_or_isolate(self) -> bool {
        matches!(
            self,
            Self::B | Self::S | Self::Ws | Self::On | Self::Fsi | Self::Lri | Self::Rli | Self::Pdi
        )
    }

    fn is_resettable_l1(self) -> bool {
        matches!(
            self,
            Self::Ws | Self::Fsi | Self::Lri | Self::Rli | Self::Pdi
        ) || self.is_removed_x9()
    }
}

/// Paragraph base-direction policy for UAX #9 (`P2–P3`).
#[cfg_attr(not(test), allow(dead_code))]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum ParagraphDir {
    /// Automatic first-strong heuristic (`P2–P3`).
    Auto,
    /// Forced left-to-right (`level = 0`).
    Ltr,
    /// Forced right-to-left (`level = 1`).
    Rtl,
}

/// Whether `character` can introduce an odd embedding level under automatic paragraph direction.
///
/// Every code point below `U+0590` has an even-only class (`L`, `EN`, `ES`, `ET`, `CS`, `NSM`,
/// `BN`, `B`, `S`, `WS`, `ON`), so pure Latin/ASCII windows pay one fast scan and zero
/// allocations.
#[inline]
pub(crate) fn may_reorder_char(character: char) -> bool {
    character >= '\u{0590}'
        && matches!(
            tables::bidi_class(character),
            BidiClass::R
                | BidiClass::Al
                | BidiClass::An
                | BidiClass::Rle
                | BidiClass::Rlo
                | BidiClass::Rli
                | BidiClass::Fsi
        )
}

/// Whether `text` contains any character that can trigger UAX #9 reordering.
pub(crate) fn may_reorder(text: &str) -> bool {
    text.chars().any(may_reorder_char)
}

/// One resolved paragraph within a laid-out window.
#[derive(Debug, Clone)]
pub(crate) struct ResolvedParagraph {
    start: usize,
    end: usize,
    para_level: u8,
    /// `(window_byte_offset, original_class, resolved_level)` for each character in the paragraph.
    chars: Vec<(usize, BidiClass, u8)>,
}

impl ResolvedParagraph {
    /// Paragraph embedding level (`0` for LTR, `1` for RTL).
    pub(crate) fn para_level(&self) -> u8 {
        self.para_level
    }

    /// Original `Bidi_Class` and resolved level for the cluster at `[offset .. offset + len)`.
    pub(crate) fn cluster_info(&self, offset: usize, len: usize) -> (BidiClass, u8) {
        let idx = match self
            .chars
            .binary_search_by(|&(byte, _, _)| byte.cmp(&offset))
        {
            Ok(found) => found,
            Err(ins) => ins.min(self.chars.len().saturating_sub(1)),
        };
        if self.chars.is_empty() {
            return (BidiClass::L, self.para_level);
        }
        let limit = offset.saturating_add(len);
        let mut cursor = idx;
        while cursor < self.chars.len() && self.chars[cursor].0 < limit {
            let (_, orig, level) = self.chars[cursor];
            if !orig.is_removed_x9() {
                return (orig, level.max(self.para_level));
            }
            cursor += 1;
        }
        let (_, orig, level) = self.chars[idx];
        (orig, level.max(self.para_level))
    }
}

/// Resolved UAX #9 state for the paragraphs of a window that need reordering.
#[derive(Debug, Clone, Default)]
pub(crate) struct WindowBidi {
    paragraphs: Vec<ResolvedParagraph>,
}

impl WindowBidi {
    /// Resolves every hard-break-delimited paragraph of `text` that contains bidirectional
    /// triggers; returns `None` when the entire window is left-to-right.
    pub(crate) fn resolve(text: &str) -> Option<Self> {
        if !may_reorder(text) {
            return None;
        }
        let bytes = text.as_bytes();
        let mut paragraphs = Vec::new();
        let mut start = 0usize;
        let mut i = 0usize;
        while i < bytes.len() {
            if bytes[i] == b'\r' {
                Self::push_if_bidi(text, start, i, &mut paragraphs);
                if i + 1 < bytes.len() && bytes[i + 1] == b'\n' {
                    i += 2;
                } else {
                    i += 1;
                }
                start = i;
            } else if bytes[i] == b'\n' {
                Self::push_if_bidi(text, start, i, &mut paragraphs);
                i += 1;
                start = i;
            } else {
                i += 1;
            }
        }
        if start <= bytes.len() {
            Self::push_if_bidi(text, start, bytes.len(), &mut paragraphs);
        }
        if paragraphs.is_empty() {
            None
        } else {
            Some(Self { paragraphs })
        }
    }

    fn push_if_bidi(text: &str, start: usize, end: usize, out: &mut Vec<ResolvedParagraph>) {
        let slice = &text[start..end];
        if !may_reorder(slice) {
            return;
        }
        let mut offsets = Vec::new();
        let mut cps = Vec::new();
        for (rel, ch) in slice.char_indices() {
            offsets.push(start + rel);
            cps.push(ch);
        }
        let (para_level, orig, levels) = resolve_raw(&cps, ParagraphDir::Auto);
        let mut chars = Vec::with_capacity(cps.len());
        for idx in 0..cps.len() {
            chars.push((offsets[idx], orig[idx], levels[idx].max(para_level)));
        }
        out.push(ResolvedParagraph {
            start,
            end,
            para_level,
            chars,
        });
    }

    /// Finds the resolved paragraph covering window-relative `offset`, if that paragraph had
    /// bidirectional triggers.
    pub(crate) fn paragraph_at(&self, offset: usize) -> Option<&ResolvedParagraph> {
        self.paragraphs
            .binary_search_by(|para| {
                if para.end < offset {
                    core::cmp::Ordering::Less
                } else if para.start > offset {
                    core::cmp::Ordering::Greater
                } else {
                    core::cmp::Ordering::Equal
                }
            })
            .ok()
            .and_then(|idx| {
                let para = &self.paragraphs[idx];
                if offset < para.end || para.start == para.end {
                    Some(para)
                } else {
                    self.paragraphs
                        .get(idx + 1)
                        .filter(|next| next.start == offset)
                }
            })
    }
}

/// Applies UAX #9 `L1.4` (reset trailing whitespace/isolates on a wrapped line to `para_level`)
/// and `L2` (reverse maximal runs from highest level down to lowest odd level), returning the
/// visual left-to-right permutation of `0..clusters.len()`.
pub(crate) fn reorder_line(para_level: u8, clusters: &mut [(BidiClass, u8)]) -> Vec<usize> {
    let len = clusters.len();
    for entry in clusters.iter_mut().rev() {
        if entry.0.is_resettable_l1() || matches!(entry.0, BidiClass::S | BidiClass::B) {
            entry.1 = para_level;
        } else {
            break;
        }
    }
    let mut order: Vec<usize> = (0..len).collect();
    let mut max_level = 0u8;
    let mut min_odd = u8::MAX;
    for &(_, level) in clusters.iter() {
        if level > max_level {
            max_level = level;
        }
        if level % 2 == 1 && level < min_odd {
            min_odd = level;
        }
    }
    if min_odd == u8::MAX {
        return order;
    }
    let mut level = max_level;
    while level >= min_odd {
        let mut i = 0usize;
        while i < len {
            if clusters[order[i]].1 >= level {
                let mut j = i + 1;
                while j < len && clusters[order[j]].1 >= level {
                    j += 1;
                }
                order[i..j].reverse();
                i = j;
            } else {
                i += 1;
            }
        }
        if level == 0 {
            break;
        }
        level -= 1;
    }
    order
}

#[derive(Clone, Copy)]
struct StatusEntry {
    level: u8,
    override_dir: Option<BidiClass>,
    isolate: bool,
}

fn type_for_level(level: u8) -> BidiClass {
    if level % 2 == 0 {
        BidiClass::L
    } else {
        BidiClass::R
    }
}

fn strong_for_neutrals(class: BidiClass) -> Option<BidiClass> {
    match class {
        BidiClass::L => Some(BidiClass::L),
        BidiClass::R | BidiClass::En | BidiClass::An => Some(BidiClass::R),
        _ => None,
    }
}

fn canonical_bracket(ch: char) -> char {
    match ch {
        '\u{2329}' => '\u{3008}',
        '\u{232A}' => '\u{3009}',
        other => other,
    }
}

/// UAX #9 `P2–P3`: paragraph embedding level from the first strong character outside isolates.
fn first_strong_level(classes: &[BidiClass]) -> u8 {
    let mut isolate_depth = 0usize;
    for &class in classes {
        if class.is_isolate_initiator() {
            isolate_depth += 1;
        } else if class == BidiClass::Pdi {
            if isolate_depth == 0 {
                break;
            }
            isolate_depth -= 1;
        } else if class == BidiClass::B && isolate_depth == 0 {
            break;
        } else if isolate_depth == 0 {
            match class {
                BidiClass::L => return 0,
                BidiClass::R | BidiClass::Al => return 1,
                _ => {}
            }
        }
    }
    0
}

/// Full UAX #9 character-level resolution (`P2–P3`, `X1–X10`, `W1–W7`, `N0–N2`, `I1–I2`, `L1`).
fn resolve_raw(cps: &[char], dir: ParagraphDir) -> (u8, Vec<BidiClass>, Vec<u8>) {
    let n = cps.len();
    let orig: Vec<BidiClass> = cps.iter().copied().map(tables::bidi_class).collect();
    let para_level = match dir {
        ParagraphDir::Ltr => 0,
        ParagraphDir::Rtl => 1,
        ParagraphDir::Auto => first_strong_level(&orig),
    };
    if n == 0 {
        return (para_level, orig, Vec::new());
    }

    // BD9: pair isolate initiators with matching PDIs in O(n).
    let mut matching_pdi: Vec<Option<usize>> = vec![None; n];
    let mut matching_init: Vec<Option<usize>> = vec![None; n];
    let mut init_stack: Vec<usize> = Vec::new();
    for (idx, &class) in orig.iter().enumerate() {
        if class.is_isolate_initiator() {
            init_stack.push(idx);
        } else if class == BidiClass::Pdi {
            if let Some(open) = init_stack.pop() {
                matching_pdi[open] = Some(idx);
                matching_init[idx] = Some(open);
            }
        } else if class == BidiClass::B {
            init_stack.clear();
        }
    }

    // X1–X8: explicit embeddings, overrides, and isolates.
    let mut classes = orig.clone();
    let mut levels = vec![para_level; n];
    let root = StatusEntry {
        level: para_level,
        override_dir: None,
        isolate: false,
    };
    let mut stack = vec![root];
    let mut overflow_isolate = 0usize;
    let mut overflow_embedding = 0usize;
    let mut valid_isolate = 0usize;

    for i in 0..n {
        let c = orig[i];
        match c {
            BidiClass::Rle | BidiClass::Rlo | BidiClass::Lre | BidiClass::Lro => {
                let top = *stack.last().unwrap_or(&root);
                levels[i] = top.level;
                if let Some(ov) = top.override_dir {
                    classes[i] = ov;
                }
                let is_rtl = matches!(c, BidiClass::Rle | BidiClass::Rlo);
                let next_lv = if is_rtl {
                    (top.level + 1) | 1
                } else {
                    (top.level + 2) & !1
                };
                if next_lv <= MAX_DEPTH && overflow_isolate == 0 && overflow_embedding == 0 {
                    let override_dir = match c {
                        BidiClass::Rlo => Some(BidiClass::R),
                        BidiClass::Lro => Some(BidiClass::L),
                        _ => None,
                    };
                    stack.push(StatusEntry {
                        level: next_lv,
                        override_dir,
                        isolate: false,
                    });
                } else if overflow_isolate == 0 {
                    overflow_embedding += 1;
                }
            }
            BidiClass::Rli | BidiClass::Lri | BidiClass::Fsi => {
                let top = *stack.last().unwrap_or(&root);
                levels[i] = top.level;
                if let Some(ov) = top.override_dir {
                    classes[i] = ov;
                }
                let is_rtl = match c {
                    BidiClass::Rli => true,
                    BidiClass::Lri => false,
                    _ => {
                        let end = matching_pdi[i].unwrap_or(n);
                        first_strong_level(&orig[i + 1..end]) == 1
                    }
                };
                let next_lv = if is_rtl {
                    (top.level + 1) | 1
                } else {
                    (top.level + 2) & !1
                };
                if next_lv <= MAX_DEPTH && overflow_isolate == 0 && overflow_embedding == 0 {
                    valid_isolate += 1;
                    stack.push(StatusEntry {
                        level: next_lv,
                        override_dir: None,
                        isolate: true,
                    });
                } else {
                    overflow_isolate += 1;
                }
            }
            BidiClass::Pdi => {
                if overflow_isolate > 0 {
                    overflow_isolate -= 1;
                } else if valid_isolate > 0 {
                    overflow_embedding = 0;
                    while stack.last().is_some_and(|entry| !entry.isolate) {
                        stack.pop();
                    }
                    stack.pop();
                    valid_isolate -= 1;
                }
                let top = *stack.last().unwrap_or(&root);
                levels[i] = top.level;
                if let Some(ov) = top.override_dir {
                    classes[i] = ov;
                }
            }
            BidiClass::Pdf => {
                let top = *stack.last().unwrap_or(&root);
                levels[i] = top.level;
                if overflow_isolate == 0 {
                    if overflow_embedding > 0 {
                        overflow_embedding -= 1;
                    } else if stack.len() >= 2 && !top.isolate {
                        stack.pop();
                    }
                }
            }
            BidiClass::B => {
                stack.clear();
                stack.push(root);
                overflow_isolate = 0;
                overflow_embedding = 0;
                valid_isolate = 0;
                levels[i] = para_level;
            }
            _ => {
                let top = *stack.last().unwrap_or(&root);
                levels[i] = top.level;
                if let Some(ov) = top.override_dir {
                    if c != BidiClass::Bn {
                        classes[i] = ov;
                    }
                }
            }
        }
    }

    // X9: retain indices not removed by X9.
    let mut kept: Vec<usize> = Vec::with_capacity(n);
    let mut pos_in_kept: Vec<usize> = vec![0; n];
    for (idx, &c) in orig.iter().enumerate() {
        if !c.is_removed_x9() {
            pos_in_kept[idx] = kept.len();
            kept.push(idx);
        }
    }

    // X10 / BD13: build level runs over `kept`, then chain isolating run sequences.
    let mut runs: Vec<Vec<usize>> = Vec::new();
    if !kept.is_empty() {
        let mut start = 0usize;
        for pos in 1..kept.len() {
            if levels[kept[pos]] != levels[kept[start]] {
                runs.push(kept[start..pos].to_vec());
                start = pos;
            }
        }
        runs.push(kept[start..].to_vec());
    }

    let mut run_of_index: Vec<Option<usize>> = vec![None; n];
    for (run_idx, run) in runs.iter().enumerate() {
        for &idx in run {
            run_of_index[idx] = Some(run_idx);
        }
    }

    let mut visited = vec![false; runs.len()];
    let mut sequences: Vec<Vec<usize>> = Vec::new();
    for run_idx in 0..runs.len() {
        let first_idx = runs[run_idx][0];
        if orig[first_idx] == BidiClass::Pdi {
            if let Some(init) = matching_init[first_idx] {
                if run_of_index[init].is_some() {
                    continue;
                }
            }
        }
        let mut seq = Vec::new();
        let mut current = Some(run_idx);
        while let Some(cur) = current {
            if visited[cur] {
                break;
            }
            visited[cur] = true;
            seq.extend_from_slice(&runs[cur]);
            let last_idx = *runs[cur].last().unwrap_or(&first_idx);
            current = if orig[last_idx].is_isolate_initiator() {
                matching_pdi[last_idx].and_then(|pdi| run_of_index[pdi])
            } else {
                None
            };
        }
        sequences.push(seq);
    }

    for seq in &sequences {
        if seq.is_empty() {
            continue;
        }
        let seq_lv = levels[seq[0]];
        let first_pos = pos_in_kept[seq[0]];
        let prev_lv = if first_pos > 0 {
            levels[kept[first_pos - 1]]
        } else {
            para_level
        };
        let sos = type_for_level(prev_lv.max(seq_lv));

        let last_idx = seq[seq.len() - 1];
        let next_lv = if orig[last_idx].is_isolate_initiator() && matching_pdi[last_idx].is_none() {
            para_level
        } else {
            let last_pos = pos_in_kept[last_idx];
            if last_pos + 1 < kept.len() {
                levels[kept[last_pos + 1]]
            } else {
                para_level
            }
        };
        let eos = type_for_level(next_lv.max(seq_lv));

        resolve_sequence(cps, &orig, seq, seq_lv, sos, eos, &mut classes);
    }

    // I1–I2: implicit levels on retained characters.
    for &idx in &kept {
        let lv = levels[idx];
        let c = classes[idx];
        if lv % 2 == 0 {
            if c == BidiClass::R {
                levels[idx] = lv + 1;
            } else if matches!(c, BidiClass::An | BidiClass::En) {
                levels[idx] = lv + 2;
            }
        } else if matches!(c, BidiClass::L | BidiClass::En | BidiClass::An) {
            levels[idx] = lv + 1;
        }
    }

    // L1.1–L1.3 & paragraph-end L1.4.
    for i in 0..n {
        if matches!(orig[i], BidiClass::S | BidiClass::B) {
            levels[i] = para_level;
            let mut j = i;
            while j > 0 {
                j -= 1;
                if orig[j].is_resettable_l1() {
                    levels[j] = para_level;
                } else {
                    break;
                }
            }
        }
    }
    let mut tail = n;
    while tail > 0 {
        tail -= 1;
        if orig[tail].is_resettable_l1() {
            levels[tail] = para_level;
        } else {
            break;
        }
    }

    (para_level, orig, levels)
}

/// Resolves weak (`W1–W7`) and neutral/bracket (`N0–N2`) rules on one isolating run sequence.
fn resolve_sequence(
    cps: &[char],
    orig: &[BidiClass],
    seq: &[usize],
    seq_lv: u8,
    sos: BidiClass,
    eos: BidiClass,
    classes: &mut [BidiClass],
) {
    let m = seq.len();
    let mut sc: Vec<BidiClass> = seq.iter().map(|&idx| classes[idx]).collect();

    // W1: NSM takes preceding type (or ON after isolate initiator / PDI).
    let mut prev = sos;
    for item in &mut sc {
        if *item == BidiClass::Nsm {
            *item = if prev.is_isolate_initiator() || prev == BidiClass::Pdi {
                BidiClass::On
            } else {
                prev
            };
        }
        prev = *item;
    }

    // W2: EN after AL becomes AN.
    let mut last_strong = sos;
    for item in &mut sc {
        if matches!(*item, BidiClass::L | BidiClass::R | BidiClass::Al) {
            last_strong = *item;
        } else if *item == BidiClass::En && last_strong == BidiClass::Al {
            *item = BidiClass::An;
        }
    }

    // W3: AL becomes R.
    for item in &mut sc {
        if *item == BidiClass::Al {
            *item = BidiClass::R;
        }
    }

    // W4: single ES between EN, or CS between matching EN/AN.
    if m >= 3 {
        for k in 1..m - 1 {
            if sc[k] == BidiClass::Es && sc[k - 1] == BidiClass::En && sc[k + 1] == BidiClass::En {
                sc[k] = BidiClass::En;
            } else if sc[k] == BidiClass::Cs
                && matches!(sc[k - 1], BidiClass::En | BidiClass::An)
                && sc[k + 1] == sc[k - 1]
            {
                sc[k] = sc[k - 1];
            }
        }
    }

    // W5: run of ET adjacent to EN becomes EN.
    let mut k = 0usize;
    while k < m {
        if sc[k] == BidiClass::Et {
            let mut end = k + 1;
            while end < m && sc[end] == BidiClass::Et {
                end += 1;
            }
            let adj_en =
                (k > 0 && sc[k - 1] == BidiClass::En) || (end < m && sc[end] == BidiClass::En);
            if adj_en {
                for item in &mut sc[k..end] {
                    *item = BidiClass::En;
                }
            }
            k = end;
        } else {
            k += 1;
        }
    }

    // W6: remaining ES, ET, CS become ON.
    for item in &mut sc {
        if matches!(*item, BidiClass::Es | BidiClass::Et | BidiClass::Cs) {
            *item = BidiClass::On;
        }
    }

    // W7: EN with last strong L becomes L.
    let mut last_strong_lr = sos;
    for item in &mut sc {
        if matches!(*item, BidiClass::L | BidiClass::R) {
            last_strong_lr = *item;
        } else if *item == BidiClass::En && last_strong_lr == BidiClass::L {
            *item = BidiClass::L;
        }
    }

    // N0 / BD16: paired brackets.
    let mut bstack: Vec<(usize, char)> = Vec::new();
    let mut pairs: Vec<(usize, usize)> = Vec::new();
    for (pos, &kind) in sc.iter().enumerate() {
        if !kind.is_neutral_or_isolate() {
            continue;
        }
        let cp = cps[seq[pos]];
        let Some((paired, is_open)) = tables::bracket(cp) else {
            continue;
        };
        if is_open {
            if bstack.len() >= MAX_PAIRING_DEPTH {
                break;
            }
            bstack.push((pos, canonical_bracket(paired)));
        } else {
            let target = canonical_bracket(cp);
            let mut found = None;
            for top in (0..bstack.len()).rev() {
                if bstack[top].1 == target {
                    found = Some(top);
                    break;
                }
            }
            if let Some(top) = found {
                pairs.push((bstack[top].0, pos));
                bstack.truncate(top);
            }
        }
    }
    pairs.sort_unstable_by_key(|&(open, _)| open);

    let embed_dir = type_for_level(seq_lv);
    let opposite_dir = if embed_dir == BidiClass::L {
        BidiClass::R
    } else {
        BidiClass::L
    };

    for (open_k, close_k) in pairs {
        let mut has_embed = false;
        let mut has_opp = false;
        for &inner in &sc[open_k + 1..close_k] {
            match strong_for_neutrals(inner) {
                Some(st) if st == embed_dir => {
                    has_embed = true;
                    break;
                }
                Some(st) if st == opposite_dir => {
                    has_opp = true;
                }
                _ => {}
            }
        }
        let resolved = if has_embed {
            Some(embed_dir)
        } else if has_opp {
            let mut ctx = sos;
            for &before in sc[..open_k].iter().rev() {
                if let Some(st) = strong_for_neutrals(before) {
                    ctx = st;
                    break;
                }
            }
            Some(if ctx == opposite_dir {
                opposite_dir
            } else {
                embed_dir
            })
        } else {
            None
        };
        if let Some(dir_class) = resolved {
            sc[open_k] = dir_class;
            sc[close_k] = dir_class;
            for base in [open_k, close_k] {
                let mut follow = base + 1;
                while follow < m && orig[seq[follow]] == BidiClass::Nsm {
                    sc[follow] = dir_class;
                    follow += 1;
                }
            }
        }
    }

    // N1–N2: remaining neutrals and isolates.
    let mut pos = 0usize;
    while pos < m {
        if sc[pos].is_neutral_or_isolate() {
            let mut end = pos + 1;
            while end < m && sc[end].is_neutral_or_isolate() {
                end += 1;
            }
            let lead = if pos > 0 {
                strong_for_neutrals(sc[pos - 1])
            } else {
                Some(sos)
            };
            let trail = if end < m {
                strong_for_neutrals(sc[end])
            } else {
                Some(eos)
            };
            let fill = match (lead, trail) {
                (Some(a), Some(b)) if a == b => a,
                _ => embed_dir,
            };
            for item in &mut sc[pos..end] {
                *item = fill;
            }
            pos = end;
        } else {
            pos += 1;
        }
    }

    for (pos, &idx) in seq.iter().enumerate() {
        classes[idx] = sc[pos];
    }
}

#[cfg(test)]
fn resolve_conformance(cps: &[char], dir: ParagraphDir) -> (u8, Vec<Option<u8>>, Vec<usize>) {
    let (para_level, orig, levels) = resolve_raw(cps, dir);
    let mut kept = Vec::new();
    let mut norm_levels = Vec::with_capacity(cps.len());
    for i in 0..cps.len() {
        if orig[i].is_removed_x9() {
            norm_levels.push(None);
        } else {
            kept.push(i);
            norm_levels.push(Some(levels[i]));
        }
    }
    let mut vis = kept;
    if !vis.is_empty() {
        let mut max_lv = 0u8;
        let mut min_odd = u8::MAX;
        for &idx in &vis {
            let lv = levels[idx];
            if lv > max_lv {
                max_lv = lv;
            }
            if lv % 2 == 1 && lv < min_odd {
                min_odd = lv;
            }
        }
        if min_odd != u8::MAX {
            let mut lv = max_lv;
            while lv >= min_odd {
                let mut i = 0;
                while i < vis.len() {
                    if levels[vis[i]] >= lv {
                        let mut j = i + 1;
                        while j < vis.len() && levels[vis[j]] >= lv {
                            j += 1;
                        }
                        vis[i..j].reverse();
                        i = j;
                    } else {
                        i += 1;
                    }
                }
                if lv == 0 {
                    break;
                }
                lv -= 1;
            }
        }
    }
    (para_level, norm_levels, vis)
}

