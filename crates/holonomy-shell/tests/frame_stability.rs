//! Hunting in the frame loop: does the editor's geometry survive being moved around?
//!
//! Every test here asserts a **confluence** property — that some sequence of harmless actions
//! returns the editor to a state it was already in, byte for byte. They are hunting tests, written
//! to fail if the loop accumulates drift rather than recomputing from the document:
//!
//! 1. A frame with nothing changed between is the **same** frame (text, origin, height, measured
//!    total). A loop that wrote its own measurements back into the index inconsistently would pass
//!    a single frame and fail the second.
//! 2. Scrolling away and back returns the same frame — and the same measured total, even though the
//!    scroll **measured leaves that the first frame never touched**. If a written-back height
//!    disagreed with what a leaf-by-leaf reflow measured, the total would move: that is the
//!    mistake this test exists to catch.
//! 3. Resizing the width and back returns the same frame at the top, because a width change empties
//!    the index and the next frame re-measures the screen from scratch.
//! 4. Undo after a resize hands back the bytes, not a stale geometry.
//! 5. Every caret a frame offers at a scroll position lies inside the frame's own text — a caret
//!    outside the window would be answered about text that is not on screen.
//!
//! The document is generated by the world-line rather than typed, so four thousand leaves cost the
//! resident set nothing; the shaper is the same deterministic fake the other shell tests use.

use holonomy_eye::{Fixed, Shaper, Style};
use holonomy_shell::Editor;
use holonomy_text::{
    Appended, ResidentSet, SegmentId, SegmentSink, SegmentSource, Slab, Spine, Typing,
};

/// One logical unit per cluster, two for `m` and `中` — as in `editing.rs`.
#[derive(Debug, Default)]
struct Fake;

impl Shaper for Fake {
    fn advance(&self, cluster: &str, _style: Style) -> Fixed {
        match cluster.chars().next() {
            Some('m') | Some('中') => Fixed::units(2),
            _ => Fixed::ONE,
        }
    }

    fn line_height(&self, _style: Style) -> Fixed {
        Fixed::units(20)
    }

    fn ascent(&self, _style: Style) -> Fixed {
        Fixed::units(15)
    }
}

/// A sink that mints distinct segment ids and stores nothing.
#[derive(Debug, Default)]
struct Recorder {
    next: u64,
}

impl SegmentSink for Recorder {
    fn append_segment(&mut self, plaintext: &[u8]) -> Result<Appended, String> {
        let id = self.next;
        self.next += 1;
        Ok(Appended {
            segment: SegmentId::new(id),
            witness_sequence: id + 1,
            segment_root: [0u8; 32],
            bytes_written: plaintext.len() as u64,
        })
    }
}

/// A world-line that generates its leaves: each is `leaf_bytes` letters and no break.
#[derive(Debug)]
struct Repeated {
    leaf_bytes: usize,
}

impl SegmentSource for Repeated {
    fn load(&mut self, segment: SegmentId) -> Result<Vec<u8>, String> {
        if segment.get() >= 4_096 {
            return Err(format!("no {segment}"));
        }
        Ok(vec![b'a'; self.leaf_bytes])
    }
}

const WIDTH: Fixed = Fixed::units(200);
const VIEWPORT: Fixed = Fixed::units(40);
/// Four leaf-sized buffers fit in the resident set; measuring is not holding.
const BUDGET: usize = 256;
/// The leaves a generated document has.
const LEAVES: usize = 4_000;

fn editor() -> Editor<Recorder, Repeated, Fake> {
    let residency =
        ResidentSet::new(Repeated { leaf_bytes: 64 }, BUDGET, 0).expect("a workable budget");
    Editor::new(
        Typing::new(Recorder::default(), 64),
        residency,
        Fake,
        WIDTH,
        VIEWPORT,
    )
}

/// A shell over a four-thousand-leaf document, fully measured.
fn measured() -> Editor<Recorder, Repeated, Fake> {
    let mut shell = editor();
    shell
        .type_text(&"a".repeat(64).repeat(LEAVES))
        .expect("typed");
    shell.flush().expect("sealed");
    shell.reflow().expect("measured");
    shell
}

/// What a frame says, copied out so the next frame can be asked for.
#[derive(Debug, PartialEq, Eq)]
struct Snapshot {
    text: String,
    origin: u64,
    height: Fixed,
    lines: usize,
    caret: Option<u64>,
}

fn snapshot(shell: &mut Editor<Recorder, Repeated, Fake>) -> Snapshot {
    let frame = shell.frame().expect("a frame");
    Snapshot {
        text: frame.text().to_owned(),
        origin: frame.origin(),
        height: frame.layout().height(),
        lines: frame.layout().lines().len(),
        caret: frame.caret().map(|caret| caret.byte),
    }
}

/// Every leaf's measured height, in leaf order.
fn heights(shell: &Editor<Recorder, Repeated, Fake>) -> Vec<Fixed> {
    let model = shell.heights();
    (0..model.len()).map(|leaf| model.height(leaf)).collect()
}

/// The first leaf whose measurement differs between two snapshots, with both numbers.
fn first_difference(before: &[Fixed], after: &[Fixed]) -> Option<(usize, i64, i64)> {
    before
        .iter()
        .zip(after)
        .position(|(one, other)| one != other)
        .map(|leaf| {
            (
                leaf,
                before[leaf].sixtyfourths(),
                after[leaf].sixtyfourths(),
            )
        })
}

#[test]
fn framing_a_screen_does_not_move_the_geometry_it_measured() {
    // A frame writes heights and carries back into the index. Whatever it writes, it must not move
    // the geometry a leaf-by-leaf `reflow` measured: the index is what the next frame reads, so a
    // write-back that disagrees with the measurement is a scroll position that means two things.
    let mut shell = measured();
    let total = shell.heights().total();
    for top in [0, 40, 400, 20_000] {
        shell.scroll_to(Fixed::units(top));
        let before = heights(&shell);
        let _ = snapshot(&mut shell);
        let after = heights(&shell);
        if let Some((leaf, was, now)) = first_difference(&before, &after) {
            panic!("at scroll {top}: the frame moved leaf {leaf} from {was} to {now}");
        }
        assert_eq!(
            shell.heights().total().sixtyfourths(),
            total.sixtyfourths(),
            "at scroll {top}: framing moved the measured total"
        );
    }
}

/// **AUDIT D-39, fixed.** Two frames at the same scroll position, with nothing edited in between,
/// used to disagree: on this document the second one started 16 bytes earlier than the first.
///
/// The cause was in the write-back, not in the frame. `Draft::spans_in` clips the leaf a window
/// begins inside, so the head span's offset is the window's own start rather than the leaf's — and
/// `measure_window` wrote that span's carries back as though they described the leaf. They do not:
/// they describe a layout beginning in the middle of it, with its first cluster at x = 0. The
/// second frame then laid the leaf out from x = 0 and found a line start at the leaf's own first
/// byte (384) instead of sixteen clusters into it (400). The heights were never wrong — the leaf
/// holds the same one line either way — which is why this only ever showed as the top line moving.
///
/// The fix: a head span is written back only when it begins on the leaf's own first byte. Its
/// heights are still written, because the lines it holds start inside it wherever the window began.
#[test]
fn a_second_frame_at_the_same_scroll_is_the_first_frame() {
    let mut shell = measured();
    for top in [0, 40, 400, 20_000] {
        shell.scroll_to(Fixed::units(top));
        let first = snapshot(&mut shell);
        let second = snapshot(&mut shell);
        assert_eq!(
            first, second,
            "at scroll {top}: two identical frames differed"
        );
    }
}

#[test]
fn scrolling_away_and_back_returns_the_same_frame() {
    let mut shell = measured();
    let total = shell.heights().total();
    shell.scroll_to(Fixed::ZERO);
    let before = snapshot(&mut shell);

    // Away: far enough that the scroll measures leaves no frame has touched yet.
    shell.scroll_to(Fixed::units(20_000));
    let deep = snapshot(&mut shell);
    assert_ne!(deep.origin, before.origin, "the deep frame is elsewhere");

    shell.scroll_to(Fixed::ZERO);
    let after = snapshot(&mut shell);
    assert_eq!(
        after, before,
        "scrolling away and back did not return the frame"
    );
    assert_eq!(
        shell.heights().total(),
        total,
        "the scroll's write-back disagreed with the reflow's measurement"
    );
}

#[test]
fn resizing_away_and_back_returns_the_same_frame_at_the_top() {
    let mut shell = measured();
    shell.scroll_to(Fixed::ZERO);
    let before = snapshot(&mut shell);

    shell.resize(Fixed::units(300), VIEWPORT);
    shell.frame().expect("a frame at the new width");
    shell.resize(WIDTH, VIEWPORT);
    // Re-measure before comparing: the point of the property is that the *wrap* round trips, not
    // that a lazily hydrated index produces the same screenful as a fully measured one.
    shell.reflow().expect("measured again");
    let after = snapshot(&mut shell);
    assert_eq!(
        after, before,
        "a width round trip did not return the frame it started from"
    );
}

#[test]
fn undo_after_a_resize_still_hands_back_the_bytes() {
    // A delete is an undo step of its own, and a resize throws the measured geometry away — the
    // question is whether it throws the history away with it.
    let mut shell = measured();
    let typed = shell.document_len();
    shell.select_all();
    assert!(shell.delete_selection().expect("deleted"), "the select-all");
    assert_eq!(shell.document_len(), 0, "everything went");
    shell.resize(Fixed::units(300), VIEWPORT);
    assert!(shell.undo().expect("undoable"), "the delete is undoable");
    assert_eq!(
        shell.document_len(),
        typed,
        "undo after a resize did not hand the document back"
    );
    let frame = shell.frame().expect("a frame");
    assert!(
        frame.text().chars().all(|cluster| cluster == 'a'),
        "the frame holds something other than the document's own letters"
    );
}

#[test]
fn every_caret_a_frame_offers_lies_inside_its_text() {
    let mut shell = measured();
    for top in [0, 20, 100, 1_000, 5_000, 20_000, 40_000] {
        shell.scroll_to(Fixed::units(top));
        let frame = shell.frame().expect("a frame");
        let origin = frame.origin();
        let end = origin + frame.text().len() as u64;
        if let Some(caret) = frame.caret() {
            assert!(
                caret.byte >= origin && caret.byte <= end,
                "at scroll {top}: caret {} is outside the frame's {origin}..{end}",
                caret.byte
            );
        }
    }
}

#[derive(Debug)]
struct ExactLeaves {
    leaves: Vec<Vec<u8>>,
}

impl SegmentSource for ExactLeaves {
    fn load(&mut self, segment: SegmentId) -> Result<Vec<u8>, String> {
        let index = usize::try_from(segment.get()).map_err(|_| format!("no {segment}"))?;
        self.leaves
            .get(index)
            .cloned()
            .ok_or_else(|| format!("no {segment}"))
    }
}

fn editor_over_leaves(
    pieces: &[&str],
    width: Fixed,
    viewport: Fixed,
) -> Editor<Recorder, ExactLeaves, Fake> {
    let mut spine = Spine::empty();
    let mut leaves = Vec::with_capacity(pieces.len());
    for (index, piece) in pieces.iter().enumerate() {
        let bytes = piece.as_bytes().to_vec();
        spine = spine.append(Slab::new(
            SegmentId::new(index as u64),
            0,
            u32::try_from(bytes.len()).expect("leaf fits u32"),
        ));
        leaves.push(bytes);
    }
    let residency = ResidentSet::new(ExactLeaves { leaves }, 4_096, 0).expect("budget");
    Editor::new(
        Typing::resume(Recorder::default(), spine, 64),
        residency,
        Fake,
        width,
        viewport,
    )
}

#[test]
fn scrolled_rtl_paragraph_across_leaves_preserves_base_direction() {
    // Leaf 0 opens an RTL paragraph ("שלום ", 5 units on line 0 at width 5); Leaf 1 holds a
    // soft-wrapped pure-ASCII continuation ("ab!") with no RTL code points of its own.
    let mut shell = editor_over_leaves(&["שלום ", "ab!"], Fixed::units(5), Fixed::units(20));
    shell.reflow().expect("measured");
    assert_eq!(shell.heights().total(), Fixed::units(40));

    shell.scroll_to(Fixed::units(20));
    let frame = shell.frame().expect("scrolled frame");
    assert_eq!(frame.text(), "ab!");
    let visual: String = frame.layout().lines()[0]
        .clusters()
        .iter()
        .map(|cluster| cluster.text)
        .collect();
    assert_eq!(
        visual, "!ab",
        "scrolled continuation must inherit RTL paragraph direction from predecessor leaf"
    );
}

#[test]
fn newline_and_wide_cluster_at_leaf_start_preserve_carries_across_frames() {
    // 1. Leaf 1 starts with '\n' after non-broken Leaf 0: frame write-back must keep `Carry.x > 0`
    //    so scrolling to line 1 starts at "hello\nend" rather than rendering a phantom blank line.
    let nl_pieces = ["abcd", "\nhello\nend"];
    let mut nl = editor_over_leaves(&nl_pieces, Fixed::units(10), Fixed::units(40));
    nl.reflow().expect("measured");
    assert_eq!(nl.heights().total(), Fixed::units(60));
    let _ = nl.frame().expect("top frame");
    assert_eq!(nl.heights().total(), Fixed::units(60));
    nl.scroll_to(Fixed::units(20));
    let scrolled = nl.frame().expect("scrolled to line 1");
    assert_eq!(scrolled.text(), "hello\nend");
    assert_eq!(nl.heights().total(), Fixed::units(60));

    // 2. Final 1-byte "\n" leaf completing a split "\r\n" owns the trailing empty line.
    let mut crlf_shell = editor_over_leaves(&["ab\r", "\n"], Fixed::units(10), Fixed::units(40));
    crlf_shell.reflow().expect("measured");
    let reflow_total = crlf_shell.heights().total();
    let _ = crlf_shell.frame().expect("frame");
    assert_eq!(reflow_total, Fixed::units(40));
    assert_eq!(crlf_shell.heights().total(), Fixed::units(40));

    // 3. Leaf 1 starts with wide '中' (`adv = 2`) wrapping after Leaf 0's `"b"` (`adv = 1`).
    let wide_pieces = ["b", "中\nx"];
    let mut wide_shell = editor_over_leaves(&wide_pieces, Fixed::units(2), Fixed::units(40));
    wide_shell.reflow().expect("measured");
    let _ = wide_shell.frame().expect("top frame");
    assert_eq!(wide_shell.heights().total(), Fixed::units(60));
    wide_shell.scroll_to(Fixed::units(20));
    let wide_scrolled = wide_shell.frame().expect("scrolled");
    assert_eq!(wide_scrolled.text(), "中\nx");
}

#[test]
fn straddling_mark_followed_by_tiny_next_leaf_keeps_single_advance() {
    // Leaf 1 ("\u{0301}b", 3 bytes) is wider than the 2-byte combining mark, while Leaf 2 ("z",
    // 1 byte) is shorter than the mark: `measure_window` must check Leaf 1's own length rather
    // than Leaf 2's when recording `skip`.
    let pieces = ["a", "\u{0301}b", "z", "\nw"];
    let mut shell = editor_over_leaves(&pieces, Fixed::units(2), Fixed::units(40));
    shell.reflow().expect("measured");
    assert_eq!(shell.heights().total(), Fixed::units(60));
    let _ = shell.frame().expect("top frame");
    assert_eq!(shell.heights().total(), Fixed::units(60));
    shell.scroll_to(Fixed::units(20));
    let second_line = shell.frame().expect("second line");
    assert_eq!(second_line.text(), "z\nw");
}
